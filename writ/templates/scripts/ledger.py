# What a decision record says and what it governs, so the whole corpus reads as one table in the
# index. Grepping the decisions directory for an area returned dozens of whole records per slice
# downstream — hundreds of thousands of tokens read to find the three that mattered.
DECISION_TITLE = re.compile(r"^#\s+\S+\s*[—-]\s*(.+?)\s*$", re.M)
DECISION_CONSTRAINS = re.compile(
    r"^\|\s*\*\*Constrains\*\*\s*\|(?P<cell>.+?)\|\s*$"
    r"|^\s*-\s+\*\*Constrains:?\*\*:?\s*(?P<bullet>.+?)\s*$",
    re.M,
)


def decision_facts(root: str, rel: str) -> tuple:
    """One record's title and what it constrains, read from the file."""
    try:
        text = read(os.path.join(root, rel))
    except OSError:
        return "", ""
    title = DECISION_TITLE.search(text)
    constrains = DECISION_CONSTRAINS.search(text)
    governs = ""
    if constrains:
        governs = " ".join((constrains.group("cell") or constrains.group("bullet") or "").split())
    return ((title.group(1).strip() if title else ""), governs)


NOT_A_DECISION = ("readme.md", "template.md")
DECISION_FILE = re.compile(r"^(\d{4})-[a-z0-9]+(?:-[a-z0-9]+)*\.md$")


def check_decisions(root: str, config: dict) -> list:
    """One file per decision number, a name the audit can read, and something it constrains.

    Two sessions in two worktrees can mint the same number on the same day, and nothing else
    notices: the suite is green and the collision is two files side by side. A malformed name is
    reported rather than skipped, because a file the duplicate check cannot read is a file it
    silently does not check. A record constraining nothing is invisible to the index — findable by
    its title and by nothing it governs."""
    directory = (config.get("decisions") or "").rstrip("/")
    here = os.path.join(root, directory)
    if not directory or not os.path.isdir(here):
        return []
    by_number, malformed = {}, []
    for name in sorted(os.listdir(here)):
        if not name.endswith(".md") or name.lower() in NOT_A_DECISION:
            continue
        found = DECISION_FILE.match(name)
        if not found:
            malformed.append(name)
            continue
        by_number.setdefault("ADR-" + found.group(1), []).append(name)
    errors = [
        directory + ": " + ident + " is two files — " + ", ".join(names)
        for ident, names in sorted(by_number.items())
        if len(names) > 1
    ]
    errors += [directory + "/" + name + ": not `NNNN-kebab-slug.md`, so no audit can read its number" for name in malformed]
    for names in by_number.values():
        for name in names:
            _title, constrains = decision_facts(root, directory + "/" + name)
            if not constrains or constrains in ("—", "-") or constrains.startswith("<"):
                errors.append(directory + "/" + name + ": names nothing it constrains, so the index cannot say what it governs")
    return errors


def render_index(root: str, config: dict, data: Collected, sections, satisfied: set) -> str:
    """One line per identifier: where it is declared and what state it is in."""
    mark = {}
    slices = {}
    for _fam, rows in sections:
        for row in rows:
            mark[row.ident] = MARK[row.status]
            slices[row.ident] = ", ".join(row.slices)
    detail = {d.ident: scalar(d.data.get("status")) for d in data.details}
    scenario = {s.ident: scalar(s.data.get("status")) for s in data.scenarios}
    questions: dict = {}
    for fam in data.families:
        if "question" not in fam.kind.lower():
            continue
        for ident in data.ids.get(fam.family, []):
            header = data.headers.get(ident, [])
            state = column(data.rows[ident], header, "Status").lower()
            if state and state.startswith("closed"):
                continue
            named = column(data.rows[ident], header, "Touches") or " ".join(data.rows[ident][1:])
            for token in re.findall(r"[A-Za-z]+-[A-Za-z0-9-]+", named):
                questions.setdefault(token, []).append(ident)

    out = [
        "<!-- Generated by `python3 scripts/ledger.py`. Do not edit by hand. -->",
        "",
        "# Index",
        "",
        "Every identifier this repository declares, where it is declared, and what state it is in.",
        "One line each, generated from the registers, the work orders, the tests, the detail files,",
        "the scenarios and the change requests. **Open this first.** Where an identifier is cited",
        "and this file does not list it, the check has already failed.",
        "",
    ]
    for fam in data.families:
        idents = sorted(set(data.ids.get(fam.family, [])) | {i for i in data.retired if family_for(i, data.families) is fam})
        if fam.family == (config.get("changes") or {}).get("family", "CR") and data.changes:
            idents = sorted({c.ident for c in data.changes})
        if not idents:
            continue
        out += ["## " + fam.family + " — " + fam.kind, ""]
        if fam.family == (config.get("changes") or {}).get("family", "CR") and data.changes:
            out += ["| ID | Where | Status | Target | Applied | Built |", "|---|---|:--:|:--:|:--:|:--:|"]
            for change in sorted(data.changes, key=lambda c: c.ident):
                applied, built = change_state(change, data, satisfied)
                out.append(
                    "| " + change.ident + " | `" + change.path + "` | " + (scalar(change.data.get("status")) or "—")
                    + " | " + (scalar(change.data.get("target")) or "—") + " | " + ("yes" if applied else "no")
                    + " | " + ("yes" if built else "no") + " |"
                )
            out.append("")
            continue
        # A family declared in the decisions directory is indexed by what each record decides and
        # what it constrains, so a slice reads one table instead of the corpus.
        decisions = (config.get("decisions") or "").rstrip("/")
        if decisions and all(data.where.get(i, "").startswith(decisions + "/") for i in idents):
            out += ["| ID | Decision | Constrains | Status | Where |", "|---|---|---|:--:|---|"]
            for ident in idents:
                where = data.where.get(ident, "")
                title, constrains = decision_facts(root, where)
                out.append(
                    "| " + ident + " | " + escape(title or "—") + " | " + escape(constrains or "—")
                    + " | " + (data.retired.get(ident) or "active") + " | `" + where + "` |"
                )
            out.append("")
            continue
        traceable = fam.traceable
        header = "| ID | Where | Status |" + (" Coverage | Slices | Detail | Scenarios | Open questions |" if traceable else " Since |")
        rule = "|---|---|:--:|" + ("---|---|:--:|:--:|---|" if traceable else ":--:|")
        out += [header, rule]
        for ident in idents:
            where = data.where.get(ident, "")
            head = data.headers.get(ident, [])
            row = data.rows.get(ident, [])
            status = data.retired.get(ident) or column(row, head, "Status") or "active"
            line = "| " + ident + " | `" + where + "` | " + status + " |"
            if traceable:
                line += (
                    " " + (mark.get(ident, "—") if ident not in data.retired else "—") + " | " + (slices.get(ident, "") or "—")
                    + " | " + (detail.get(ident) or "—") + " | " + (scenario.get(ident) or "—")
                    + " | " + (", ".join(sorted(set(questions.get(ident, [])))) or "—") + " |"
                )
            else:
                line += " " + (column(row, head, "Since") or "—") + " |"
            out.append(line)
        out.append("")
    if data.orders:
        out += ["## SL — slice", "", "| ID | Where | Phase | Status | Advances |", "|---|---|:--:|:--:|---|"]
        for order in sorted(data.orders, key=lambda o: o.slice_id):
            out.append(
                "| " + order.slice_id + " | `" + order.path + "` | " + (order.phase or "—") + " | " + order.status
                + " | " + (", ".join(order.satisfies + [p + " (partial)" for p in order.partial]) or "—") + " |"
            )
        out.append("")
    return "\n".join(out).rstrip() + "\n"


# The statuses that mean somebody has claimed the slice. A `queued` or `blocked` work order is a
# plan, and planning sixty-four issues into a tracker nobody reads is how a tracker stops being read.
TRACKED = ("in-progress", "in-review", "done")

# An open slice, for the checks that read a work order as a live document rather than a record.
# A done work order records what was agreed; a later convention makes it history, not wrong.
OPEN = ("in-progress", "in-review")
BRACKETED = re.compile(r"\[(?P<id>[A-Za-z][A-Za-z0-9]*(?:-[A-Za-z0-9.]+)+)\]")


def section_named(body: str, wanted: str) -> str:
    """The text under the first heading whose normalised title equals `wanted`."""
    lines = body.split("\n")
    start, level = None, 0
    for index, depth, raw in headings(lines):
        if start is None:
            if normalise(raw) == wanted:
                start, level = index, depth
            continue
        if depth <= level:
            return "\n".join(lines[start + 1 : index])
    return "" if start is None else "\n".join(lines[start + 1 :])


def criteria(section: str) -> list:
    """The numbered items of an Acceptance criteria section, one string per item. An item with
    nothing after its number is a template's empty slot, not a criterion."""
    found, current = [], None
    for line in section.split("\n"):
        if line.lstrip().startswith(">"):
            continue
        if re.match(r"^\s*\d+\.\s+\S", line):
            if current:
                found.append(current)
            current = line.strip()
        elif current is not None and line.strip():
            current += " " + line.strip()
        elif current:
            found.append(current)
            current = None
    if current:
        found.append(current)
    return found


CHARACTERISATION = "characterisation"
KINDS = ("feature", CHARACTERISATION)


def check_process(root: str, config: dict, data: Collected, unknown, satisfied=frozenset(), backfill=None) -> list:
    errors = list(data.errors)
    errors += check_details(config, data, set(satisfied))
    errors += check_scenarios(config, data)
    errors += check_files(root, config, data)
    errors += check_annotations(root, config, data)
    errors += check_changelog(root, config, data)
    errors += check_references(root, config, data)
    errors += check_decisions(root, config)
    errors += check_paths(root, config)
    context_errors, context_warnings = check_context(root, config)
    errors += context_errors
    data.warnings += context_warnings
    errors += check_changes(config, data, set(satisfied))
    order_errors, order_warnings = check_order(backfill)
    errors += order_errors
    data.warnings += order_warnings
    codes = [str(p.get("code") or p.get("letter") or "") for p in (config.get("phases") or [])]

    for path, ident, fam in unknown:
        errors.append(path + ": [" + ident + "] is not declared in " + fam + "'s section")

    seen = {}
    for order in data.orders:
        if order.slice_id in seen:
            errors.append(order.path + ": slice id " + order.slice_id + " is already used by " + seen[order.slice_id])
        seen[order.slice_id] = order.path

        # An ADR named by a work order exists before implementation starts. A decision recorded
        # after the fact is a justification; the record is only worth keeping if it precedes
        # the code it governs.
        for adr in order.adr:
            number = adr.split("-", 1)[-1]
            here = os.path.join(root, config["decisions"])
            candidates = []
            for stem in (number, adr, adr.lower()):
                candidates += glob.glob(os.path.join(here, stem + "-*.md"))
                candidates += glob.glob(os.path.join(here, stem + ".md"))
            if not candidates:
                errors.append(order.path + ": names " + adr + ", and no such record exists in " + config["decisions"])

        if order.kind not in KINDS:
            errors.append(order.path + ": kind is " + order.kind + ", not one of " + ", ".join(KINDS))

        # A slice is not demonstrable in the abstract. Either a script a reader can paste, or
        # numbered steps through an interface with a stated expected observation.
        #
        # A characterisation slice is the exception, and it is the only one. It changes no
        # behaviour, so there is nothing to demonstrate that was not demonstrable yesterday —
        # `demo: none` says so. What replaces the demonstration is not nothing: the section must
        # still say what behaviour is now pinned, because the question a characterisation slice
        # gets wrong is *whether the behaviour it froze was the behaviour anybody wanted*. A test
        # written from the code asserts the bug as confidently as the feature.
        demo = demo_section(order.body)
        if not demo.strip():
            errors.append(order.path + ": has no Demo section")
        else:
            blocks = [b for b in FENCE.findall(demo) if [l for l in b.split("\n") if l.strip() and not l.strip().startswith("#")]]
            steps = NUMBERED.findall(demo)
            if order.demo == "none":
                if order.kind != CHARACTERISATION:
                    errors.append(
                        order.path + ": demo is `none`, which only a `kind: characterisation` slice may say —"
                        + " a slice that changes behaviour is played by hand"
                    )
                elif len(demo.split()) < 20:
                    errors.append(
                        order.path + ": is characterisation and its Demo section does not say what behaviour"
                        + " it pinned, or how anyone confirmed that behaviour is wanted"
                    )
            elif order.demo == "ui":
                if len(steps) < 2 or "expected" not in demo.lower():
                    errors.append(order.path + ": demo is `ui` and needs numbered steps and an Expected line")
            elif not blocks:
                errors.append(order.path + ": demo is `script` and carries no runnable code block")
            for hit in placeholders(demo):
                errors.append(order.path + ": demo still carries the placeholder " + hit + " — nobody types an identifier")

        # **Acceptance criteria are read against the front matter** while the slice is open. Each
        # becomes a test name and a test name carries its identifier, so a criterion naming none
        # proves nothing the ledger can see, and one naming an identifier the front matter does
        # not claim is a claim made in prose, which no ledger, queue or coverage row will find.
        if order.status in OPEN and order.kind != CHARACTERISATION:
            claimed = set(order.satisfies) | set(order.partial)
            for item in criteria(section_named(order.body, "acceptancecriteria")):
                named = BRACKETED.findall(item)
                if not named:
                    errors.append(
                        order.path + ": acceptance criterion `" + item[:60].rstrip()
                        + "` names no identifier — it becomes a test name, and a test name says what it proves"
                    )
                for ident in named:
                    if ident not in claimed:
                        errors.append(
                            order.path + ": acceptance criterion names " + ident
                            + ", which the front matter does not claim — a claim made in prose reaches no ledger"
                        )

        errors += check_size(config, order)

        # A slice is a global, zero-padded number, and its file is named for that number: the
        # identifier encodes nothing else, so nothing about it goes stale when the slice moves
        # phase or splits. The phase is a column, a directory, and a line of front matter.
        stem = os.path.splitext(os.path.basename(order.path))[0]
        number = order.slice_id.split("-")[-1]
        if stem != number and stem != order.slice_id:
            errors.append(order.path + ": is " + order.slice_id + " and its file is not named " + number + ".md")
        if codes and order.phase and order.phase not in codes:
            errors.append(order.path + ": declares phase " + order.phase + ", which is not one of " + ", ".join(codes) + " in ledger.config.json")

        # A work order filed under a phase directory must be the phase it declares. The directory
        # is how a person finds it; the front matter is how the queue orders it. When they
        # disagree the queue is right and the reader is wrong, which is the worse way round.
        sub_dir = os.path.dirname(os.path.relpath(order.path, config["work_orders"]))
        if sub_dir and order.phase:
            leaf = os.path.basename(sub_dir)
            if leaf != order.phase:
                errors.append(
                    order.path + ": sits in phase directory " + leaf + " and declares phase " + order.phase
                )

        # The tracker holds narrative and linkage; the work order holds the record. `issue:` is
        # the one place the two are tied together, and it is written at the moment of claiming —
        # so the number is known before the branch exists and the close commit's `Closes #N` has
        # something to resolve. `—` is the grandfathered value: a slice that landed before the
        # tracker did, which no number can be invented for after the fact.
        if config.get("tracker") and order.status in TRACKED:
            if not order.issue:
                errors.append(
                    order.path + ": status is " + order.status + " and it names no issue —"
                    + " open one at the claim and record it as `issue:`"
                )
            elif order.issue != "—" and not order.issue.isdigit():
                errors.append(
                    order.path + ": issue is " + order.issue
                    + ", which is neither a number nor `—` for a slice that predates the tracker"
                )

        if order.status == "done":
            candidates = slice_paths(root, config, order)
            if not any(os.path.exists(c) for c in candidates):
                errors.append(
                    order.path + ": status is done and " + os.path.relpath(candidates[0], root) + " does not exist"
                )

    limit = int(config.get("wip_limit") or 0)
    if limit:
        active = [o for o in data.orders if o.status in ("in-progress", "in-review")]
        if len(active) > limit:
            errors.append("work in progress is " + str(len(active)) + ", over the limit of " + str(limit))
        for i, one in enumerate(active):
            for other in active[i + 1 :]:
                shared = sorted(set(one.touches) & set(other.touches))
                if shared:
                    errors.append(
                        one.slice_id + " and " + other.slice_id + " are both active and both touch "
                        + ", ".join(shared) + " — serialise them or split the surface"
                    )

    scan = config.get("placeholder_scan", {})
    for path in iter_files(root, scan.get("include", []), scan.get("exclude", [])):
        for line_no, line in prose_lines(read(path)):
            for hit in placeholders(line):
                errors.append(
                    os.path.relpath(path, root) + ":" + str(line_no) + ": unresolved placeholder " + hit
                )

    return errors


