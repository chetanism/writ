def bare(cell: str) -> str:
    """Strip emphasis and code fencing from a table cell so `**INV-1**` reads as `INV-1`."""
    return cell.replace("*", "").replace("`", "").strip()


def normalise(heading: str) -> str:
    """Lowercase, alphanumerics only — so `§9 Functional requirements` finds `## 9. Functional
    requirements`. The registry stays readable; the matcher does the work."""
    return re.sub(r"[^a-z0-9]", "", heading.lower())


def cells(line: str) -> list:
    """Split a Markdown table row into its cells."""
    body = line.strip()
    if body.startswith("|"):
        body = body[1:]
    if body.endswith("|"):
        body = body[:-1]
    return [c.strip() for c in body.split("|")]


def is_separator(line: str) -> bool:
    return bool(re.match(r"^\s*\|[\s:|-]+\|\s*$", line))


def escape(text: str) -> str:
    return text.replace("|", "\\|").strip()


# The opening or closing line of a fenced block, compiled once: it is asked of every line of every
# scanned document, and on a large tree that was hundreds of thousands of lookups per `check`.
FENCE_LINE = re.compile(r"^\s*(```|~~~)")


def headings(lines) -> list:
    """(index, level, title) for every heading, ignoring anything inside a fenced code block.

    A shell comment inside a ```bash block matches the heading pattern exactly. Reading one as a
    heading truncates whatever section it sits in, which is how a demo script full of `#` comments
    becomes an empty demo section."""
    found, fenced = [], False
    for index, line in enumerate(lines):
        if FENCE_LINE.match(line):
            fenced = not fenced
            continue
        if fenced:
            continue
        head = re.match(r"^(#{1,6})\s+(.*)$", line)
        if head:
            found.append((index, len(head.group(1)), head.group(2)))
    return found


def read(path: str) -> str:
    with open(path, encoding="utf-8") as handle:
        return handle.read()


# An exclusion that names a directory subtree is a **question about a path**, not a set of paths.
# Expanding `**/node_modules/**` with `glob.glob` enumerates every file of every installed package
# — half a million paths and most of a minute on a real monorepo — only to discard them. Matched
# per path instead, the same exclusion costs nothing.
SUBTREE_EXCLUSION = re.compile(r"^(?:\*\*/)?(?P<body>[^*?\[\]]+?)/\*\*$")


def subtree_exclusion(pattern: str):
    """`**/node_modules/**` → a segment name; `writ/process/templates/**` → a path prefix.

    `None` for anything else — a pattern naming files rather than a subtree keeps the glob, because
    it is cheap and because guessing at its meaning is how an exclusion silently stops excluding."""
    hit = SUBTREE_EXCLUSION.match(pattern)
    if not hit:
        return None
    body = hit.group("body").strip("/")
    return ("segment", body) if pattern.startswith("**/") and "/" not in body else ("prefix", body)


def iter_files(root: str, includes, excludes=()) -> list:
    """Expand glob patterns relative to `root`, deterministically, honouring exclusions.

    The same answer `glob.glob(..., recursive=True)` gives — hidden names are matched only when the
    pattern spells them — but an excluded subtree is pruned from the walk rather than listed and
    then discarded, so `**/*.test.ts` beside `**/node_modules/**` never enters `node_modules`.

    **The gain is for unrooted `**/` includes only.** A glob rooted in a directory that holds no
    excluded subtree — `apps/*/src/**/*.test.ts` — never entered one before either, and walks in the
    same time now."""
    subtrees, excluded = [], set()
    for pattern in excludes:
        subtree = subtree_exclusion(pattern)
        if subtree:
            subtrees.append(subtree)
        else:
            excluded.update(os.path.normpath(p) for p in glob.glob(os.path.join(root, pattern), recursive=True))

    def in_excluded_subtree(rel: str, is_dir: bool = False) -> bool:
        segments = rel.split("/")
        for kind, body in subtrees:
            if kind == "segment" and body in (segments if is_dir else segments[:-1]):
                return True
            if kind == "prefix" and (rel == body or rel.startswith(body + "/")):
                return True
        return False

    found = set()
    for pattern in includes:
        pattern = pattern.replace(os.sep, "/")
        parts = pattern.split("/")
        literal = []
        for part in parts:
            if glob.has_magic(part):
                break
            literal.append(part)
        if len(literal) == len(parts) or "**" not in pattern:
            # A literal path or a shallow glob is cheap to expand as written.
            hits = glob.glob(os.path.join(root, pattern), recursive=True)
        else:
            hits = walk_matching(root, "/".join(literal), pattern, in_excluded_subtree)
        for hit in hits:
            hit = os.path.normpath(hit)
            rel = os.path.relpath(hit, root).replace(os.sep, "/")
            if hit in excluded or in_excluded_subtree(rel):
                continue
            if os.path.isfile(hit):
                found.add(hit)
    return sorted(found)


def walk_matching(root: str, base: str, pattern: str, pruned) -> list:
    """Files under `root/base` matching a `**` pattern, never descending into a pruned directory.

    Names beginning with `.` below `base` are skipped, as `glob` skips them: a pattern reaches a
    hidden directory only by spelling it, and a spelled name is part of `base`."""
    regex = glob_regex(pattern)
    start = os.path.join(root, base) if base else root
    hits = []
    for here, dirs, files in os.walk(start):
        rel_here = os.path.relpath(here, root).replace(os.sep, "/")
        rel_here = "" if rel_here == "." else rel_here
        dirs[:] = sorted(
            d for d in dirs
            if not d.startswith(".") and not pruned((rel_here + "/" + d).lstrip("/"), True)
        )
        for name in files:
            if name.startswith("."):
                continue
            rel = (rel_here + "/" + name).lstrip("/")
            if regex.match(rel):
                hits.append(os.path.join(here, name))
    return hits


def perimeter(config: dict, rule: str) -> list:
    """The path patterns one rule is in force over.

    A named rule **replaces** the default rather than adding to it, so a perimeter can be narrowed
    below the default as well as widened past it — `work_order` over one directory while
    `annotations` covers the repository is the ordinary shape of a half-adopted project, and a
    union could not express it. `null` in the config means *inherit the default*, which is
    different from `[]`, meaning *enclose nothing*.
    """
    block = config.get("enforce")
    if not isinstance(block, dict):
        return []
    paths = block.get(rule)
    if paths is None:
        paths = block.get("default")
    return [str(p) for p in (paths or [])]


@functools.lru_cache(maxsize=None)
def glob_regex(pattern: str) -> "re.Pattern":
    """One `**`-aware glob pattern, compiled to match a path relative to the root.

    Matching rather than expanding, and the difference is not stylistic. The default perimeter is
    `**`, and expanding that with `glob.glob` walks every file in the repository — `node_modules`,
    build output, the lot — to answer a question that only ever gets asked about paths already in
    hand. On a large project that is seconds per run, on every run.

    The same language as the globs everywhere else in this config: `**` spans directories, `*` and
    `?` stop at a separator."""
    out = []
    i = 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            out.append("(?:.*/)?")  # zero or more directories, so `**/x` matches a bare `x`
            i += 3
        elif pattern.startswith("**", i):
            out.append(".*")
            i += 2
        elif pattern[i] == "*":
            out.append("[^/]*")
            i += 1
        elif pattern[i] == "?":
            out.append("[^/]")
            i += 1
        else:
            out.append(re.escape(pattern[i]))
            i += 1
    return re.compile("".join(out) + r"\Z")


def within(rel: str, patterns) -> bool:
    """Whether one path, relative to the root, falls inside a perimeter."""
    here = rel.replace(os.sep, "/")
    return any(glob_regex(p).match(here) for p in patterns)


# --------------------------------------------------------------------------------------------
# A minimal YAML front-matter reader
# --------------------------------------------------------------------------------------------
#
# Deliberately not a YAML implementation. Work-order front matter is scalars, inline lists and
# block lists, and nothing else — a restriction the template states and this parser enforces by
# not understanding anything more. A dependency for eight fields would be the wrong trade.


def strip_comment(raw: str) -> str:
    """Drop a trailing `# ...` comment, as YAML does — a `#` opens one only after whitespace.

    The templates carry an aligned comment on half their front-matter lines (`status: queued
    # queued | in-progress | ...`), so a drafter who fills one in and leaves the comment is doing
    the obvious thing. Without this, `status` reads as the whole line and every check that compares
    it silently stops working."""
    value = raw.strip()
    if value[:1] in ("\"", "'"):
        end = value.find(value[0], 1)
        if end != -1:
            return value[: end + 1]
        return value
    cut = re.search(r"(?:^|\s)#", value)
    return value[: cut.start()].strip() if cut else value


def parse_scalar(raw: str):
    value = strip_comment(raw)
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    if value in ("true", "false"):
        return value == "true"
    if value in ("null", "~", ""):
        return None
    if re.fullmatch(r"-?\d+", value):
        return int(value)
    return value


def parse_front_matter(text: str):
    """Return (mapping, body). A file with no front matter yields ({}, text)."""
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        return {}, text
    try:
        end = next(i for i in range(1, len(lines)) if lines[i].strip() == "---")
    except StopIteration:
        return {}, text

    data: dict = {}
    key = None
    for line in lines[1:end]:
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        item = re.match(r"^\s*-\s+(.*)$", line)
        if item and key is not None:
            data.setdefault(key, [])
            if isinstance(data[key], list):
                data[key].append(parse_scalar(item.group(1)))
            continue
        pair = re.match(r"^([A-Za-z_][A-Za-z0-9_]*)\s*:\s*(.*)$", line)
        if not pair:
            continue
        key, raw = pair.group(1), strip_comment(pair.group(2))
        if raw.startswith("[") and raw.endswith("]"):
            inner = raw[1:-1].strip()
            data[key] = [parse_scalar(p) for p in inner.split(",")] if inner else []
        elif raw == "":
            data[key] = []
        else:
            data[key] = parse_scalar(raw)
    return data, "\n".join(lines[end + 1 :])


def as_int(value) -> int:
    """A front-matter number, or 0 for a field nobody has filled in yet. Blank rather than absent
    is the normal state of both size fields: one is written at open and one at close."""
    if isinstance(value, bool) or value in (None, ""):
        return 0
    if isinstance(value, int):
        return value
    text = str(value).strip().replace(",", "")
    return int(text) if re.fullmatch(r"\d+", text) else 0


def as_list(value) -> list:
    if value is None:
        return []
    if isinstance(value, list):
        return [str(v) for v in value if v not in (None, "")]
    return [str(value)] if str(value) else []


