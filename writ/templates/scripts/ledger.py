# A placeholder is anything in angle brackets that is not markup: `<N>`, `<the gate commands>`,
# `<150>` and `<test:all>` all count. Case is not a signal — the templates use every shape — so the
# exemptions are for what Markdown itself carries: HTML tags, comments, and autolinked URLs.
PLACEHOLDER = re.compile(r"<([^<>\n]{1,80})>")
HTML_TAG = re.compile(r"^/?(?:a|b|i|p|br|hr|em|img|kbd|pre|sub|sup|div|span|code|strong|table|thead|tbody|tr|td|th|ul|ol|li|details|summary)(?:\s[^>]*)?/?$", re.I)


def placeholders(text: str) -> list:
    """Every unresolved `<...>` in `text`, in order, with the brackets kept for the message."""
    found = []
    for match in PLACEHOLDER.finditer(text):
        inner = match.group(1)
        if inner[0] in "!?" or inner[0].isspace() or inner[-1].isspace():
            continue  # a comment, a processing instruction, or `a < b > c` in prose
        if "://" in inner or inner.startswith("mailto:") or re.fullmatch(r"[^\s@]+@[^\s@]+", inner):
            continue  # an autolink
        if HTML_TAG.match(inner):
            continue
        found.append("<" + inner + ">")
    return found
FENCE = re.compile(r"```[^\n]*\n(.*?)```", re.S)
NUMBERED = re.compile(r"^\s*\d+\.\s+\S", re.M)


INLINE_CODE = re.compile(r"`[^`\n]*`")


def prose_lines(text: str):
    """(line number, line) for every line of prose — outside fenced blocks, outside inline code,
    and outside blockquotes.

    Code is notation, not a gap: `/slice-open <id>`, `slice/<ID>-<slug>` and `git diff
    <last-pass>..HEAD` are how a finished document describes a shape, and they must survive. A
    blockquote is guidance that the bootstrap deletes. What is left is where a placeholder to fill
    can only be a placeholder — which is why the templates keep theirs out of backticks."""
    fenced = False
    for number, line in enumerate(text.split("\n"), start=1):
        if FENCE_LINE.match(line):
            fenced = not fenced
            continue
        if fenced or line.strip().startswith(">"):
            continue
        yield number, INLINE_CODE.sub("`…`", line)


def demo_section(body: str) -> str:
    """The text under the first heading whose title starts with `Demo`."""
    lines = body.split("\n")
    start, level = None, 0
    for index, depth, raw in headings(lines):
        if start is None:
            if normalise(raw).startswith("demo"):
                start, level = index, depth
            continue
        if depth <= level:
            return "\n".join(lines[start + 1 : index])
    return "" if start is None else "\n".join(lines[start + 1 :])


# --------------------------------------------------------------------------------------------
# The size budget
# --------------------------------------------------------------------------------------------
#
# `DEVELOPMENT-PROCESS.md` §2.1: *a diff one person can read carefully in under thirty minutes*.
# It is a comprehension budget, and the whole design rests on it — the limit exists precisely
# because an agent can produce far more than that in a session. It was also the one budget in the
# kit with no check behind it, while the far smaller context budget had a warning, a ceiling and a
# named remedy. **A budget with no remedy is a rule people learn to route around**, and a budget
# with no check is one nobody has to route around at all.
#
# What is checkable here is not the diff — this tool never runs git, and a check that did could not
# run on a merge commit. What is checkable is the work order's own two statements about itself: the
# tier it declares and the number it recorded at close. Holding those together is the same move the
# ledger makes on a `satisfies` claim, pointed at the claim a slice makes about its own size.


def size_tiers(config: dict) -> list:
    """[(tier, ceiling)] in order. An empty budget turns the whole check off."""
    budget = config.get("size_budget")
    if not isinstance(budget, dict):
        return []
    return [(str(name), int(ceiling or 0)) for name, ceiling in budget.items()]


def tier_of(tiers: list, lines: int) -> str:
    """The tier a measurement falls in. The last tier has no ceiling and catches the rest."""
    for name, ceiling in tiers:
        if ceiling and lines <= ceiling:
            return name
    return tiers[-1][0] if tiers else ""


def size_section(body: str) -> str:
    """The text under the first heading whose title starts with `Size`."""
    lines = body.split("\n")
    start, level = None, 0
    for index, depth, raw in headings(lines):
        if start is None:
            if normalise(raw).startswith("size"):
                start, level = index, depth
            continue
        if depth <= level:
            return "\n".join(lines[start + 1 : index])
    return "" if start is None else "\n".join(lines[start + 1 :])


def check_size(config: dict, order: WorkOrder) -> list:
    """What one work order says about its own size, held to the tiers."""
    tiers = size_tiers(config)
    if not tiers:
        return []
    names = [name for name, _ceiling in tiers]
    errors = []

    if order.size and order.size not in names:
        errors.append(
            order.path + ": size is " + order.size + ", not one of " + ", ".join(names)
            + " in ledger.config.json"
        )
        return errors

    # The measurement decides, and the declared tier is what the queue shows a reader. A slice
    # that came in at 420 lines is an L whatever it was estimated at; correcting the tier is the
    # honest move and `estimated` is where the original guess survives it.
    if order.code_lines and order.size:
        actual = tier_of(tiers, order.code_lines)
        if actual != order.size:
            errors.append(
                order.path + ": declares size " + order.size + " and records " + str(order.code_lines)
                + " code lines, which is " + actual + " — correct `size:`, which is what the queue"
                + " shows; `estimated:` is where the original guess belongs"
            )

    # The top tier is the one that has to argue for itself. Everything else is within a budget
    # somebody already agreed to.
    if order.size and order.size == names[-1]:
        said = [
            line for line in size_section(order.body).split("\n")
            if line.strip() and not line.strip().startswith(">")
        ]
        if len(said) < 2:
            errors.append(
                order.path + ": is " + order.size + " and its Size section says only what it"
                + " measured — an " + order.size + " states why it could not be split, or it is two"
                + " slices that have not been separated yet"
            )
    return errors


