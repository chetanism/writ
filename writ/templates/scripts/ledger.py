# Stats — is the process working?
# --------------------------------------------------------------------------------------------
#
# Everything else here answers *do the documents agree with each other*, at one moment. Nothing
# answered *is this process being followed*, which is a different question and the one that goes
# wrong slowly: the tiers that were never recalibrated, the audit nobody has run since June, the
# detail track that stopped at requirement nine. `DEVELOPMENT-PROCESS.md` §2.1 asks for exactly
# this — *recalibrate these tiers from measurement after the first ten slices* — and there was no
# way to measure.
#
# It never fails. A number here is something to look at at a phase gate, not a gate.

STATUS_ORDER = ("in-progress", "in-review", "blocked", "queued", "done")


def median(values: list) -> int:
    ordered = sorted(values)
    if not ordered:
        return 0
    middle = len(ordered) // 2
    if len(ordered) % 2:
        return ordered[middle]
    return (ordered[middle - 1] + ordered[middle]) // 2


def open_rows(text: str) -> int:
    """Rows under an `## Open` heading. The backlogs keep four tables and only one is live."""
    count = 0
    for line in section_lines(text, "Open"):
        stripped = line.strip()
        if not stripped.startswith("|") or is_separator(line):
            continue
        col = cells(line)
        if col and bare(col[0]) and bare(col[0]).lower() != "id":
            count += 1
    return count


def days_since(day: str) -> int:
    import datetime

    try:
        then = datetime.date(*[int(p) for p in day.split("-")])
    except (TypeError, ValueError):
        return -1
    return (datetime.date.today() - then).days


def render_graph(config: dict, data: Collected, sections, counts) -> str:
    """The trace graph as JSON, on stdout.

    Everything here is already assembled for the ledger; this hands it over in a shape something
    other than a person can read — a dashboard, a badge, a report that spans several repositories,
    or a migration to some other tool. That last one is the point. A process kit that can only be
    read by its own renderer is a lock-in, and the argument this kit makes about documents applies
    to it too: if the data cannot leave, the claim that it is *your* data is decorative.

    Like `stats`, it reads everything, writes nothing, and cannot fail a build.
    """
    graph = {
        "version": 1,
        "generated_by": "ledger.py graph",
        "mode": scalar(config.get("mode", "")),
        "counts": dict(counts, total=sum(counts.values())),
        "families": [
            {
                "family": fam.family,
                "pattern": fam.pattern,
                "owner": fam.owner,
                "traceable": bool(fam.traceable),
            }
            for fam in data.families
        ],
        "requirements": [
            {
                "id": row.ident,
                "family": fam.family,
                "state": row.status,
                "claimed_by": list(row.slices),
                "proven_by": list(row.proofs),
                # The ledger's own distinction, carried over rather than left to be re-derived:
                # a claim with no test behind it is not the same as nothing having been claimed.
                "claimed_without_proof": bool(row.unproven),
            }
            for fam, rows in sections
            for row in rows
        ],
        "slices": [
            {
                "id": order.slice_id,
                "title": order.title,
                "phase": order.phase,
                "kind": order.kind,
                "status": order.status,
                "size": order.size,
                "estimated": order.estimated,
                "code_lines": order.code_lines,
                "depends_on": list(order.depends_on),
                "satisfies": list(order.satisfies),
                "partial": list(order.partial),
            }
            for order in sorted(data.orders, key=lambda o: o.slice_id)
        ],
    }
    return json.dumps(graph, indent=2, sort_keys=False, ensure_ascii=False) + "\n"


def from_velocity(root: str, name: str, *args) -> list:
    """Lines from one of `scripts/velocity.py`'s summaries, or nothing. This file never calls git
    itself, and stats never fails: without the tool, without a repository or without history it
    says nothing."""
    here = os.path.join(root, "scripts", "velocity.py")
    if not os.path.exists(here):
        return []
    try:
        import importlib.util

        spec = importlib.util.spec_from_file_location("velocity", here)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        return list(getattr(module, name)(root, *args))
    except Exception:  # a report, not a gate: a broken neighbour costs one section, not the command
        return []


def velocity_lines(root: str) -> list:
    lines = from_velocity(root, "summary")
    return lines + [""] if lines else []


def backfill_lines(root: str, config: dict, data: Collected, sections) -> list:
    """Whether the backfill is catching up with the build — printed while there is one to watch.

    The number that matters under `out_of_order: backfill` is not the size of the gap but its
    direction. A gap that keeps growing is the signal to slow the build down, and whether to is the
    owner's call; this puts the number in front of them."""
    found = assess_order(config, data, sections)
    if found is None or not (found.mode == "backfill" or found.ahead or found.unreconciled):
        return []
    spec = config.get("requirements") or {}
    aimed = [e for e in found.ahead if e[1] and e[1] in found.active]
    out = ["Backfill — out_of_order: " + found.mode]
    out.append(
        "  " + "built ahead".ljust(15) + str(len(found.ahead)) + " requirements with no detail file"
        + (" · " + str(len(aimed)) + " aimed at " + ", ".join(found.active) + ", the active milestone" if aimed else "")
    )
    if found.unreconciled:
        out.append(
            "  " + "to reconcile".ljust(15) + str(len(found.unreconciled)) + " slices against "
            + str(len({d.ident for d, _o in found.unreconciled})) + " detail files"
        )
    families = [str(f) for f in (spec.get("families") or [])]
    eligible = {i for fam, ids in data.ids.items() for i in ids if not families or fam in families}
    claims = {o.slice_id: sorted(i for i in set(o.satisfies) | set(o.partial) if i in eligible) for o in data.orders}
    out += from_velocity(root, "backfill_summary", claims, spec.get("dir") or "")
    return out + [""]


def render_stats(root: str, config: dict, data: Collected, sections, counts) -> str:
    out = []

    # -- the queue -------------------------------------------------------------------------
    by_status = {}
    for order in data.orders:
        by_status.setdefault(order.status, []).append(order)
    shape = ", ".join(
        str(len(by_status[s])) + " " + s for s in STATUS_ORDER if by_status.get(s)
    )
    out += ["SL — " + str(len(data.orders)) + " slices: " + (shape or "none")]
    for phase in config.get("phases") or []:
        code = str(phase.get("code") or "")
        here = [o for o in data.orders if o.phase == code]
        if not here:
            continue
        done = [o for o in here if o.status == "done"]
        active = [o.slice_id for o in here if o.status in ("in-progress", "in-review")]
        line = "  " + code.ljust(5) + str(phase.get("name") or "").ljust(22)
        line += (str(len(done)) + "/" + str(len(here)) + " done").ljust(12)
        out.append(line + (" · " + ", ".join(active) + " in flight" if active else ""))
    out.append("")

    # -- sizing, which is the whole reason this subcommand exists ---------------------------
    tiers = size_tiers(config)
    measured = [o for o in data.orders if o.code_lines]
    if tiers and measured:
        out.append("Size — " + str(len(measured)) + " slices measured")
        for name, ceiling in tiers:
            here = [o.code_lines for o in measured if o.size == name]
            if not here:
                continue
            budget = "budget " + str(ceiling) if ceiling else "no ceiling"
            out.append(
                "  " + name.ljust(5) + str(len(here)).rjust(3) + "   median "
                + str(median(here)).ljust(6) + "  (" + budget + ")"
            )
        # The estimate is never corrected, so this is the only place the two can be compared —
        # and three misses in the same direction is a finding about the tiers, not about a slice.
        guessed = [o for o in measured if o.estimated]
        if guessed:
            held = [o for o in guessed if tier_of(tiers, o.estimated) == tier_of(tiers, o.code_lines)]
            over = [o for o in guessed if o.code_lines > o.estimated]
            out.append(
                "  estimate held its tier in " + str(len(held)) + " of " + str(len(guessed))
                + " · " + str(len(over)) + " came in over the estimate"
            )
        out.append("")

    # -- coverage ---------------------------------------------------------------------------
    out.append("Coverage — " + str(counts[SATISFIED]) + " satisfied of " + str(sum(counts.values())))
    for fam, rows in sections:
        tally = {state: 0 for state in STATES}
        for row in rows:
            tally[row.status] += 1
        unproven = len([r for r in rows if r.unproven])
        line = "  " + fam.family.ljust(6)
        line += "".join(MARK[k] + " " + str(tally[k]).ljust(4) for k in STATES)
        out.append(line + ("  " + str(unproven) + " claimed with no test behind them" if unproven else ""))
    out.append("")

    # -- adoption ---------------------------------------------------------------------------
    #
    # Printed only while it has something to say: a perimeter narrower than everything, or a row
    # proven by evidence older than the process. A project bootstrapped greenfield has neither and
    # never sees this block. A project adopting into an existing codebase reads nothing else as
    # often, because these are the numbers somebody has to take to four colleagues who have not
    # agreed to any of this yet.
    rules = [(rule, perimeter(config, rule)) for rule in ("annotations", "work_order")]
    # A `Provenance` column is what an adopted register carries and a greenfield one does not:
    # `decided` is a row somebody chose, `observed` is a row read off the code. The count still
    # `observed` is the documentation backlog, and it is the number that says how much of this
    # specification describes behaviour rather than stating intent — including, silently, every
    # bug old enough that somebody now relies on it.
    marked = [column(cells, data.headers.get(ident, []), "provenance") for ident, cells in data.rows.items()]
    observed = len([v for v in marked if v.lower() == "observed"])
    if counts[INHERITED] or observed or any(paths != ["**"] for _rule, paths in rules):
        out.append("Adoption — what this process is in force over")
        for rule, paths in rules:
            out.append("  " + rule.ljust(13) + (", ".join(paths) if paths else "nothing — not in force"))
        tests = config.get("tests") or {}
        files = [os.path.relpath(f, root) for f in iter_files(root, tests.get("globs", []), tests.get("exclude", []))]
        if files:
            named = {rel for _i, _p, rel in data.annotations}
            guarded = [f for f in files if within(f, perimeter(config, "annotations"))]
            out.append(
                "  " + "test files".ljust(13) + str(len([f for f in files if f in named])) + " of "
                + str(len(files)) + " name a requirement · " + str(len(guarded)) + " inside the perimeter"
            )
        if counts[INHERITED]:
            out.append(
                "  " + "inherited".ljust(13) + str(counts[INHERITED])
                + " rows proven by tests no work order claimed — the characterisation queue"
            )
        if observed:
            out.append(
                "  " + "observed".ljust(13) + str(observed) + " of " + str(len([v for v in marked if v]))
                + " rows are still read off the code rather than decided"
            )
        out.append("")

    # -- the parallel tracks ----------------------------------------------------------------
    tracks = []
    for label, spec_key, filed in (
        ("detail", "requirements", {d.ident: scalar(d.data.get("status")) for d in data.details}),
        ("scenarios", "scenarios", {s.ident: scalar(s.data.get("status")) for s in data.scenarios}),
    ):
        spec = config.get(spec_key) or {}
        if not spec.get("dir"):
            continue
        families = [str(f) for f in (spec.get("families") or [])]
        covered = [i for fam, ids in data.ids.items() if not families or fam in families for i in ids]
        reviewed = len([i for i in covered if filed.get(i) == "reviewed"])
        draft = len([i for i in covered if filed.get(i) not in (None, "reviewed")])
        tracks.append(
            "  " + label.ljust(11) + "reviewed " + str(reviewed) + " · draft " + str(draft)
            + " · none " + str(len(covered) - reviewed - draft) + "   of " + str(len(covered))
            + " requirements the track covers"
        )
    if tracks:
        out += ["Tracks — beside the loop"] + tracks + [""]

    # -- work that arrived out of order -----------------------------------------------------
    out += backfill_lines(root, config, data, sections)

    # -- the standing records ---------------------------------------------------------------
    here = os.path.join(root, config.get("maintenance") or "")
    if config.get("maintenance") and os.path.isdir(here):
        lines = []
        for name in sorted(os.listdir(here)):
            if not name.endswith(".md") or name.lower() == "readme.md":
                continue
            lines.append("  " + name.ljust(24) + str(open_rows(read(os.path.join(here, name)))) + " open")
        audits = os.path.join(here, "audits")
        dated = sorted(re.findall(r"(\d{4}-\d{2}-\d{2})", " ".join(os.listdir(audits)))) if os.path.isdir(audits) else []
        if dated:
            age = days_since(dated[-1])
            lines.append("  " + "last audit".ljust(24) + dated[-1] + (" · " + str(age) + " days ago" if age >= 0 else ""))
        elif os.path.isdir(audits):
            lines.append("  " + "last audit".ljust(24) + "never — /security-audit has not run")
        if lines:
            out += ["Standing records"] + lines + [""]

    # -- velocity, from git, when there is a repository and the tool beside this one ---------
    out += velocity_lines(root)

    # -- the agent map ----------------------------------------------------------------------
    budget = config.get("context_budget") or {}
    for rel in budget.get("files") or []:
        path = os.path.join(root, rel)
        if os.path.exists(path):
            out.append(
                "Context — " + rel + " " + str(len(read(path))) + " of "
                + str(budget.get("warn_chars") or 0) + " characters budgeted"
            )
    return "\n".join(line.rstrip() for line in out).rstrip() + "\n"


