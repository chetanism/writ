        "",
        "# Requirement coverage",
        "",
        "Generated from four sources, none of them a list maintained beside the specification:",
        "",
        "- `" + config["registry"] + "` — which families are traceable",
        "- each family's declaring section — which identifiers exist",
        "- `" + config["work_orders"] + "/*.md` front matter — what each slice claimed",
        "- `[ID]`-annotated test names — what is actually proven",
        "",
        "A claim of `satisfies` with no annotated test behind it is recorded as **partial**, not",
        "satisfied, and listed below. A ledger that believes its own work orders is a spreadsheet.",
