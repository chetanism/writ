#!/usr/bin/env python3
"""Traceability tooling: the coverage ledger, the slice queue, and the process checks.

Generated by the `bootstrap` kit. Stdlib only, Python 3.9+.

    python3 scripts/ledger.py                    write the ledger and the queue block
    python3 scripts/ledger.py ledger [--check]   just the coverage ledger
    python3 scripts/ledger.py queue  [--check]   just the generated queue block
    python3 scripts/ledger.py check              verify both, plus every process check — CI runs this
    python3 scripts/ledger.py stats              is the process being followed? reports, never fails

The contract, in one paragraph. `ID-REGISTRY.md` declares identifier *families* — never
identifiers. Each family names the document and the section that declares its IDs. An identifier
is declared if and only if it is the first cell of a table row, under a header row beginning
`| ID |`, inside that section. Work orders claim IDs in their YAML frontmatter. Tests prove them
by carrying `[ID]` in a test name. This tool joins the four sources and writes the result down.

Nothing here knows a prefix. Adding a family is a Markdown row, never a code change.

Beyond coverage, the check holds the documents to one rule: **a file holds one kind of thing, and
status is a column**. A register file carries exactly one `| ID |` table and a narrative file
carries none; a register row's `Status` retires an identifier and its `Since` names what
introduced it; history lives in one changelog, one line per amendment; every identifier mentioned
in prose resolves to a declared one; and `INDEX.md` is generated so a reader can find any of them.

Two more sources are checked and never counted. `requirements.dir` holds one detail file per
requirement — what it means, told as stories — and `scenarios.dir` holds the manual test scenarios
written from that file. Neither changes a status: a requirement is proven by its tests. But each
quotes its requirement verbatim, and this verifies the quote, so an amended specification fails
every file that has not been re-read.
"""

