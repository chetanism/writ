def write_or_check(root: str, rel: str, content: str, check: bool) -> list:
    path = os.path.join(root, rel)
    if check:
        current = read(path) if os.path.exists(path) else ""
        if current != content:
            return [rel + " is stale. Run `python3 scripts/ledger.py`."]
        return []
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(content)
    return []


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Coverage ledger, slice queue, and process checks.")
    parser.add_argument("command", nargs="?", default="all", choices=["all", "ledger", "queue", "check", "stats", "graph", "annotations"])
    parser.add_argument("ids", nargs="*", help="annotations: the identifiers to look up (default: all)")
    parser.add_argument("--check", action="store_true", help="verify without writing")
    parser.add_argument("--root", default=".", help="project root")
    parser.add_argument("--config", default="scripts/ledger.config.json")
    args = parser.parse_args(argv)

    root = os.path.abspath(args.root)
    config = load_config(root, args.config)
    verify = args.check or args.command == "check"

    if args.command == "annotations":
        # Which test files name each identifier, as JSON — what `scripts/falsify.py` runs instead of
        # the whole suite. Reads only the test files, so it answers in the time the globs take.
        sys.stdout.write(json.dumps(annotated_files(root, config, args.ids), indent=2, sort_keys=True) + "\n")
        return 0

    data = collect(root, config)
    sections, counts, unknown, unregistered, unclaimable = build_ledger(data)
    ordered, order_errors = order_slices(data.orders, config.get("phases", []))
    backfill = assess_order(config, data, sections)

    if args.command == "graph":
        # Same contract as `stats`: an instrument, not a gate.
        sys.stdout.write(render_graph(config, data, sections, counts))
        return 0

    if args.command == "stats":
        # Reads everything and writes nothing, including the exit code. It is an instrument, and
        # an instrument that can fail a build is a gate wearing a different name.
        sys.stdout.write(render_stats(root, config, data, sections, counts))
        return 0

    errors = []
    satisfied = {r.ident for _f, rows in sections for r in rows if r.status == SATISFIED}
    if args.command in ("all", "ledger", "check"):
        # Read the ledger being replaced before replacing it. This is the only moment the previous
        # state is still on disk, and a lost proof is invisible afterwards.
        here = os.path.join(root, config["coverage_out"])
        if os.path.exists(here):
            data.warnings += lost_proof(previous_marks(read(here)), sections)
        errors += write_or_check(
            root,
            config["coverage_out"],
            render_ledger(config, sections, counts, unregistered, unclaimable, data.details, data.scenarios, backfill),
            verify,
        )
        if config.get("index_out"):
            errors += write_or_check(root, config["index_out"], render_index(root, config, data, sections, satisfied), verify)

    if args.command in ("all", "queue", "check") and config.get("queue_out"):
        queue_path = os.path.join(root, config["queue_out"])
        if not os.path.exists(queue_path):
            errors.append(config["queue_out"] + " does not exist")
        else:
            spliced = splice_queue(read(queue_path), render_queue(config, ordered))
            if spliced is None:
                errors.append(config["queue_out"] + " has no " + QUEUE_BEGIN + " … " + QUEUE_END + " block")
            else:
                errors += write_or_check(root, config["queue_out"], spliced, verify)

    errors += order_errors
    if args.command == "check":
        errors += check_process(root, config, data, unknown, satisfied, backfill)
    else:
        errors += [p + ": [" + i + "] is not declared in " + f + "'s section" for p, i, f in unknown]
        errors += data.errors

    # Warnings before errors, so the errors are the last thing on the terminal. A warning is a
    # finding with a pass of its own to fix it; it never decides the exit code.
    for message in sorted(set(data.warnings)):
        sys.stderr.write("warning: " + message + "\n")

    for message in sorted(set(errors)):
        sys.stderr.write("error: " + message + "\n")

    if not errors and args.command in ("all", "ledger", "check"):
        sys.stdout.write(
            "coverage: " + ", ".join(str(counts[k]) + " " + k for k in STATES)
            + ", " + str(sum(counts.values())) + " total\n"
        )
    return 1 if errors else 0


if __name__ == "__main__":
    raise SystemExit(main())
