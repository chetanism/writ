def check_annotations(root: str, config: dict, data: Collected) -> list:
    """Inside the `annotations` perimeter, a test file names at least one identifier.

    The ledger has always *counted* annotations and never *demanded* them, which is right
    greenfield — a slice that forgets them fails on its own unproven claim, because the work order
    said what it would prove. Nothing says it on a codebase whose tests predate every work order:
    eight hundred unannotated tests are eight hundred pieces of evidence the ledger cannot see,
    and no existing check notices, because no claim was ever made.

    This is the cheapest rule in the kit and the first one worth turning on repository-wide.
    Annotating an existing test is seven characters and no design work, and it is what moves a row
    from `○` to `≈` without writing a line of new test.

    **File-level by default**, deliberately. Finding every test *case* across stacks means a second
    pattern that has to be right, and a wrong one either misses cases or invents them. A file with
    no annotation at all is unambiguous, language-agnostic, and the failure that actually happens
    — somebody adds a test file and never hears about this process. Set `tests.case` to a pattern
    matching one test declaration to get the stricter count as well.
    """
    paths = perimeter(config, "annotations")
    if not paths:
        return []
    tests = config.get("tests") or {}
    files = [
        p for p in iter_files(root, tests.get("globs", []), tests.get("exclude", []))
        if within(os.path.relpath(p, root), paths)
    ]
    if not files:
        return []

    # Distinct annotated test *names* per file. `data.annotations` is deduplicated, so two tests
    # proving one identifier count twice and one test naming two identifiers counts once — which
    # is the right way round for comparing against a count of declarations.
    named = {}
    for _ident, proof, rel in data.annotations:
        named.setdefault(rel, set()).add(proof)

    case = None
    if tests.get("case"):
        try:
            case = re.compile(tests["case"])
        except re.error as bad:
            return ["tests.case is not a valid regular expression: " + str(bad)]

    errors = []
    for path in files:
        rel = os.path.relpath(path, root)
        found = named.get(rel, set())
        if not found:
            errors.append(
                rel + ": inside the annotations perimeter and names no requirement —"
                + " every test here starts with its identifier, `[<ID>] …`"
            )
            continue
        if case is None:
            continue
        try:
            cases = len(case.findall(read(path)))
        except (UnicodeDecodeError, OSError):
            continue
        if cases > len(found):
            errors.append(
                rel + ": has " + str(cases) + " tests and " + str(len(found))
                + " annotated — the unannotated ones prove nothing the ledger can see"
            )
    return errors


def known_ids(data: Collected) -> set:
    """Everything a reference may resolve to: live identifiers, retired ones — a withdrawn
    requirement is still cited — slices, and change requests."""
    found = {i for ids in data.ids.values() for i in ids}
    found |= set(data.retired)
    found |= {o.slice_id for o in data.orders}
    found |= {c.ident for c in data.changes}
    return found


def proposed_ids(data: Collected) -> set:
    """Every identifier named in a change request's *Changes* table.

    An `add` row names a row that does not exist yet — that is the whole point of raising one — so
    the reference scan would otherwise fail every draft request for the identifier it is asking
    for, and the owner could never be shown a green pull request to decide on. These resolve for
    the reference scan and for nothing else: `check_changes` still holds each row to its family's
    pattern, and still refuses an accepted request whose rows are not in the registers."""
    return {ident for change in data.changes for _op, ident, _col in change_rows(change.body) if ident}


def check_files(root: str, config: dict, data: Collected) -> list:
    """A register carries exactly one `| ID |` table; a narrative carries none; a `Since` names
    what introduced the row, and it exists."""
    errors = []
    for path in iter_files(root, config.get("registers") or []):
        count = id_tables(read(path))
        if count != 1:
            errors.append(
                os.path.relpath(path, root) + ": a register carries exactly one `| ID |` table, and this "
                "carries " + str(count) + (" — one kind of thing per file" if count else " — a register with nothing declared is a narrative")
            )
    for path in iter_files(root, config.get("narrative") or []):
        count = id_tables(read(path))
        if count:
            errors.append(
                os.path.relpath(path, root) + ": a narrative document declares nothing, and this carries "
                + str(count) + " `| ID |` table" + ("s" if count > 1 else "") + " — registers live in their own files"
            )
    resolvable = known_ids(data)
    for ident, header in sorted(data.headers.items()):
        since = column(data.rows[ident], header, "Since")
        if "since" not in header:
            continue
        if not since:
            errors.append(data.where[ident] + ": " + ident + " has an empty Since — the version, amendment or change request that introduced it")
        elif not VERSION_TAG.match(since) and since not in resolvable:
            errors.append(data.where[ident] + ": " + ident + " says Since " + since + ", which is neither a version tag nor a declared amendment or change request")
    return errors


def changelog_header(text: str) -> list:
    """The header cells of the file's `| ID |` table, lowercased, or `[]` where it carries none."""
    for line in text.split("\n"):
        if not line.strip().startswith("|") or is_separator(line):
            continue
        col = cells(line)
        if col and bare(col[0]).lower() == "id":
            return [bare(c).lower() for c in col]
    return []


def check_changelog(root: str, config: dict, data: Collected) -> list:
    """One line per amendment: dated, naming what it touched, and short enough to be a line."""
    rel = config.get("changelog") or ""
    path = os.path.join(root, rel)
    if not rel or not os.path.exists(path):
        return []
    limit = int(config.get("changelog_max_chars") or 240)
    resolvable = known_ids(data)
    families = [f for f in data.families]
    errors = []
    rows = declared_rows_with_headers(read(path), "*")
    # Read from the table itself rather than from a row, so a changelog nobody has written a line
    # in yet is still held to its shape. The rows all share one header; any of them will do.
    header = rows[0][2] if rows else changelog_header(read(path))
    for name in ("date", "touches", "change", "cause"):
        if name not in header:
            return [rel + ": the changelog table has no " + name.capitalize() + " column"]
    for ident, col, header in rows:
        where = rel + ": " + ident + " "
        date = column(col, header, "Date")
        if not DATE.match(date):
            errors.append(where + "has the date " + (date or "empty") + ", which is not YYYY-MM-DD")
        touches = column(col, header, "Touches")
        if not touches.strip():
            errors.append(where + "touches nothing — name the identifiers it changed, or the version it bumped")
        for token in re.split(r"[,\s]+", touches):
            if not token or VERSION_TAG.match(token) or token in resolvable:
                continue
            if family_for(token, families) is not None or re.match(r"^[A-Za-z]+-\d", token):
                errors.append(where + "touches " + token + ", which is not declared anywhere")
        for name in ("Change", "Cause"):
            text = column(col, header, name)
            if len(text) > limit:
                errors.append(
                    where + name + " is " + str(len(text)) + " characters, over the " + str(limit)
                    + " a changelog line gets — the reasoning belongs in an ADR or the slice summary, linked from here"
                )
    return errors


def sections_of(text: str) -> list:
    """(heading, characters) for every `## ` section, in file order; text above the first is
    `(preamble)`. A `## ` inside a fenced block is code, not a section."""
    out, heading, size, fenced = [], "(preamble)", 0, False
    for line in text.split("\n"):
        if FENCE_LINE.match(line):
            fenced = not fenced
        if not fenced and line.startswith("## "):
            out.append((heading, size))
            heading, size = line[3:].strip(), 0
        size += len(line) + 1
    out.append((heading, size))
    return [(h, n) for h, n in out if n]


def largest_sections(text: str) -> str:
    """The three sections a compaction pass should look at first, largest first."""
    top = sorted(sections_of(text), key=lambda pair: -pair[1])[:3]
    return "; ".join(h + " (" + str(n) + ")" for h, n in top)


def check_context(root: str, config: dict) -> tuple:
    """What is read at the start of every session is paid for on every task. Returns
    `(errors, warnings)`: over the budget is a warning, because the remedy is a pass of its own
    and not the slice that happened to add the last line; over the ceiling is an error, because
    by then the agent map has stopped being a map.

    Either message names the three largest sections, because *the file is too long* sends the
    reader to read the whole file to find out where."""
    budget = config.get("context_budget") or {}
    warn = int(budget.get("warn_chars") or 0)
    ceiling = int(budget.get("max_chars") or 0)
    errors, warnings = [], []
    for rel in budget.get("files") or []:
        path = os.path.join(root, rel)
        if not os.path.exists(path):
            continue
        text = read(path)
        size = len(text)
        if ceiling and size > ceiling:
            errors.append(
                rel + " is " + str(size) + " characters, over the ceiling of " + str(ceiling)
                + " — run `/context-compact` before this lands: it moves sections out and leaves a pointer."
                + " Largest sections: " + largest_sections(text)
            )
        elif warn and size > warn:
            warnings.append(
                rel + " is " + str(size) + " characters, over the " + str(warn)
                + " budgeted for a file read at the start of every session — `/context-compact` moves"
                + " sections out, and the next line added here replaces two."
                + " Largest sections: " + largest_sections(text)
            )
    return errors, warnings


def check_references(root: str, config: dict, data: Collected) -> list:
    """Every identifier-shaped token in prose resolves. A dangling reference is a defect, found
    here rather than by the reader who follows it."""
    scan = config.get("reference_scan") or {}
    fallback = config.get("placeholder_scan") or {}
    includes = scan.get("include") or fallback.get("include") or []
    excludes = list(scan.get("exclude") or fallback.get("exclude") or [])
    for key in ("coverage_out", "index_out"):
        if config.get(key):
            excludes.append(config[key])
    resolvable = known_ids(data) | proposed_ids(data)
    patterns = [(f, re.compile(r"(?<![A-Za-z0-9-])" + f.regex + r"(?![A-Za-z0-9-])")) for f in data.families]
    # One cheap question before many expensive ones. Most prose lines hold no identifier-shaped
    # token at all, so the union of every family answers *could anything match here* in one pass
    # and the per-family loop runs only for the lines that survive it — on a large tree it was
    # three quarters of `check`'s time.
    candidate = re.compile("|".join("(?:" + f.regex + ")" for f in data.families)) if data.families else None
    errors = []
    for path in iter_files(root, includes, excludes):
        rel = os.path.relpath(path, root)
        # Fenced blocks and blockquotes are notation and guidance — a trailer example, a
        # template's worked sample — and inline code is a citation, so it is scanned.
        fenced = False
        for number, line in enumerate(read(path).split("\n"), start=1):
            if FENCE_LINE.match(line):
                fenced = not fenced
                continue
            if fenced or line.strip().startswith(">"):
                continue
            if candidate is None or not candidate.search(line):
                continue
            for fam, pattern in patterns:
                for hit in pattern.finditer(line):
                    token = hit.group(0)
                    if token not in resolvable:
                        errors.append(rel + ":" + str(number) + ": " + token + " is not declared anywhere it could be")
    return sorted(set(errors))


# A path cited in a standing document resolves, as an identifier does. `check_references` says
# nothing about `writ/process/DEVELOPMENT-PROCESS.md`, so deleting or renaming a document leaves
# every citation to it dangling with the gate green.
#
# **Only an anchored path is checked** — one whose first segment is a top-level entry of this
# repository. Prose is full of paths relative to a directory the sentence already named
# (`templates/slice-summary.md`, `spec/README.md`), and guessing a base for those turns a handful
# of real findings into hundreds of false ones; a check that cries wolf on prose is one nobody
# keeps. An anchored citation is the form a document reference takes, and the only form a deletion
# can dangle.
INLINE_CODE = re.compile(r"`([^`\n]+)`")
PATH_SHAPED = re.compile(r"^[A-Za-z0-9._@/-]+$")
NOTATION = ("*", "?", "<", ">", "{", "}", "[", "]", "$", "\u2026", "://")


def cited_path(token: str, anchors: frozenset) -> bool:
    """Is this inline-code token a path this repository claims exists at its root?"""
    if "/" not in token or not PATH_SHAPED.match(token) or token.startswith(("/", "~", ".")):
        return False
    if any(mark in token for mark in NOTATION):
        return False
    if token.split("/", 1)[0] not in anchors:
        return False
    # A bare `packages/db` is a name; `packages/db/` and `scripts/ledger.py` are claims.
    return token.endswith("/") or bool(os.path.splitext(token)[1])


def check_paths(root: str, config: dict) -> list:
    """Every anchored path cited in inline code in a standing document is there.

    A record — a work order, a slice summary, a decision, a change request, an audit — was true
    when it was written, so a path that has since moved is history rather than a defect; keep
    records out of `path_scan`. `allow` lists paths named deliberately as absent: build output, a
    file a decision removed and the prose still explains. One auditable list beats de-backticking
    the prose."""
    scan = config.get("path_scan") or {}
    includes = scan.get("include") or []
    if not includes:
        return []
    excludes = list(scan.get("exclude") or [])
    for key in ("coverage_out", "index_out"):
        if config.get(key):
            excludes.append(config[key])
    allowed = frozenset(scan.get("allow") or [])
    anchors = frozenset(name for name in os.listdir(root) if not name.startswith(".git"))
    errors = []
    for path in iter_files(root, includes, excludes):
        rel = os.path.relpath(path, root)
        fenced = False
        for number, line in enumerate(read(path).split("\n"), start=1):
            if FENCE_LINE.match(line):
                fenced = not fenced
                continue
            if fenced:
                continue
            for token in INLINE_CODE.findall(line):
                token = token.strip()
                if token in allowed or not cited_path(token, anchors):
                    continue
                if not os.path.exists(os.path.join(root, token)):
                    errors.append(rel + ":" + str(number) + ": " + token + " is cited and is not there")
    return sorted(set(errors))


# --------------------------------------------------------------------------------------------
# Change requests
# --------------------------------------------------------------------------------------------
#
# After launch, the registers are the store and a change request is the unit of change: one file
# with the rows it adds, amends or withdraws, accepted by the specification's owner and then
# applied mechanically. The file's own state is derived — applied when its rows are in the
# registers, built when every one of its identifiers reads satisfied — so "did January's change
# ship" is a lookup rather than a question.

CHANGE_STATUSES = ("draft", "reviewed", "accepted", "rejected")
CHANGE_OPS = ("add", "amend", "withdraw")
CHANGE_KEYS = ("id", "status", "requested_by", "approved_by", "decided_on", "target")
CHANGE_SECTIONS = ("The job", "Changes", "Impact", "Decision")


def change_rows(body: str) -> list:
    """(op, identifier, cells) per row of the *Changes* table."""
    found, in_table, header = [], False, []
    for line in section_lines(body, CHANGE_SECTIONS[1]):
        stripped = line.strip()
        if not stripped.startswith("|"):
            in_table = False
            continue
        if is_separator(line):
            continue
        col = cells(line)
        if col and bare(col[0]).lower() == "op":
            in_table, header = True, [bare(c).lower() for c in col]
            continue
        if in_table and bare(col[0]):
            found.append((bare(col[0]).lower(), column(col, header, "ID"), col))
    return found


def change_state(change, data: Collected, satisfied: set):
    """(applied, built) — derived from the registers and the ledger, never written down."""
    applied, built = True, True
    for op, ident, _col in change_rows(change.body):
        if op == "withdraw":
            applied = applied and ident in data.retired
            continue
        since = column(data.rows.get(ident, []), data.headers.get(ident, []), "Since")
        applied = applied and since == change.ident
        built = built and ident in satisfied
    return applied, built


def check_changes(config: dict, data: Collected, satisfied: set) -> list:
    spec = config.get("changes") or {}
    if not spec.get("dir"):
        return []
    known = known_ids(data)
    families = data.families
    errors = []
    for change in data.changes:
        where = change.path + ": "
        if not change.data:
            errors.append(where + "has no front matter")
            continue
        for key in (k for k in CHANGE_KEYS if k != "approved_by"):
            if scalar(change.data.get(key)).strip() in BLANK and key != "decided_on":
                errors.append(where + "front matter has no " + key)
        status = scalar(change.data.get("status"))
        if status not in CHANGE_STATUSES:
            errors.append(where + "status is " + (status or "empty") + ", not one of " + ", ".join(CHANGE_STATUSES))
        if status in ("accepted", "rejected"):
            if scalar(change.data.get("approved_by")).strip() in BLANK:
                errors.append(where + "is " + status + " and names nobody who decided it")
            if not DATE.match(scalar(change.data.get("decided_on")).strip()):
                errors.append(where + "is " + status + " and decided_on is not a date")
        target = scalar(change.data.get("target")).strip()
        if target and target not in known:
            errors.append(where + "targets " + target + ", which is not a declared milestone")
        present = section_titles(change.body)
        for title in CHANGE_SECTIONS:
            if normalise(title) not in present:
                errors.append(where + "has no " + title + " section")
        rows = change_rows(change.body)
        if not rows:
            errors.append(where + "changes nothing — a change request names at least one row to add, amend or withdraw")
        for op, ident, _col in rows:
            if op not in CHANGE_OPS:
                errors.append(where + "row " + (ident or "?") + " has the op " + op + ", not one of " + ", ".join(CHANGE_OPS))
                continue
            fam = family_for(ident, families)
            if fam is None or not fam.traceable:
                errors.append(where + "row " + ident + " is not an identifier a change request can change")
                continue
            if not re.fullmatch(fam.regex, ident):
                errors.append(where + "row " + ident + " does not fit the " + fam.family + " pattern " + fam.pattern)
            declared = ident in data.rows
            since = column(data.rows.get(ident, []), data.headers.get(ident, []), "Since") if declared else ""
            if op == "withdraw":
                if status == "accepted" and ident not in data.retired:
                    errors.append(where + "is accepted and " + ident + " is not withdrawn in its register")
                if ident not in known:
                    errors.append(where + "withdraws " + ident + ", which is not declared")
                continue
            if op == "amend" and ident not in known:
                errors.append(where + "amends " + ident + ", which is not declared")
            if status == "accepted" and since != change.ident:
                errors.append(
                    where + "is accepted and " + ident + (" is not in its register" if not declared else " does not say Since " + change.ident)
                    + " — apply the request: write the row, set Since, add the changelog line"
                )
            if status != "accepted" and since == change.ident:
                errors.append(where + "is " + status + " and " + ident + " already says Since " + change.ident + " — applied before it was accepted")
    return errors


# --------------------------------------------------------------------------------------------
# Out of order
# --------------------------------------------------------------------------------------------
#
# One requirement's documents arrive in an order — detail file, work order, code — and in practice
# the order breaks all the time: a slice builds a requirement nobody has detailed, or a detail file
# is revised after the slice that built it. Neither is an exception to plan around. What matters is
# that it is **found** — mechanically, not by somebody remembering to look — and that each conflict
# ends in a decision somebody made rather than in whichever document happened to be written last.
#
# Three signals are cheap and exact, and they are all this reads. It never reads code:
#
# 1. **Built ahead of its detail** — a slice claims a requirement that has no detail file.
# 2. **Built against an older reading** — a slice read the detail file on `detail_read_on`, or
#    recorded no reading at all, and the file's `revised_on` is later. The build may still hold;
#    somebody has to say so, in a *Reconciliation* row dated no earlier than the revision.
# 3. **A closed milestone that is not caught up** — built requirements aimed at it still undetailed,
#    unreviewed or unreconciled.
#
# How loudly each one speaks is `requirements.out_of_order`, and one rule holds in every mode but
# `report`: once a requirement's detail file is `reviewed`, a slice that drifts from it fails.
# Backfilling is allowed to lag. A requirement it has caught up with is not allowed to slip again.

OUT_OF_ORDER = ("fail", "backfill", "report")
RECONCILIATION = "Reconciliation"
RECONCILE_COLUMNS = ("Date", "Against", "Conflict", "Decision", "Where", "By")
# What a reconciliation can conclude. `holds` — the build matches the current reading. `ratified`
# — the build made a choice the requirement did not, and its owner has taken it as intended.
# `fix` — the build is wrong, and the slice that corrects it is named. `change-request` — the
# specification is wrong, and the request that changes it is named. `open` — nobody present can
# decide; on a reviewed file it names the registered question that holds it.
RECONCILE_DECISIONS = ("holds", "ratified", "fix", "change-request", "open")
# A milestone whose `Status` begins with one of these has finished, and its requirements are held
# to having caught up.
CLOSED_MILESTONE = ("done", "shipped", "released", "closed")
BUILDING = ("in-progress", "in-review")
TOKEN = re.compile(r"[A-Za-z][A-Za-z0-9]*(?:-[A-Za-z0-9]+)+")


def reconciliation_rows(body: str) -> list:
    """Every row under *Reconciliation*, as a mapping of lowercased column name to its cell."""
    found, in_table, header = [], False, []
    for line in section_lines(body, RECONCILIATION):
        if not line.strip().startswith("|"):
            in_table = False
            continue
        if is_separator(line):
            continue
        col = cells(line)
        if col and bare(col[0]).lower() == "date":
            in_table, header = True, [bare(c).lower() for c in col]
            continue
        if in_table and any(bare(c) for c in col):
            found.append({name.lower(): column(col, header, name) for name in RECONCILE_COLUMNS})
    return found


@dataclass
class Backfill:
    """What arrived out of order, read once and shared by the check, the ledger and `stats`."""

    mode: str
    # (ident, target, built by, still to come, why first) — built and never detailed, most urgent first
    ahead: list = field(default_factory=list)
    # (order, ident) — a building or finished slice claiming a requirement with no detail file
    claimed_ahead: list = field(default_factory=list)
    # orders building eligible requirements that never recorded reading their detail files
    unread: list = field(default_factory=list)
    # (detail, order) — built against an older reading, and no reconciliation says it still holds
    unreconciled: list = field(default_factory=list)
    # (milestone, ident, what is missing)
    milestone: list = field(default_factory=list)
    errors: list = field(default_factory=list)  # malformed rows and settings, in every mode
    active: list = field(default_factory=list)  # the milestones marked `active`


def milestone_states(data: Collected) -> dict:
    """{milestone: the first word of its Status, lowercased} for every family whose kind names a
    milestone — `active`, `planned`, `done`."""
    found = {}
    for fam in data.families:
        if "milestone" not in fam.kind.lower():
            continue
        for ident in data.ids.get(fam.family, []):
            words = column(data.rows.get(ident, []), data.headers.get(ident, []), "Status").lower().split()
            found[ident] = words[0] if words else ""
    return found


def assess_order(config: dict, data: Collected, sections) -> Backfill | None:
    """What arrived out of order. `None` where the detail track is not installed."""
    spec = config.get("requirements") or {}
    if not spec.get("dir"):
        return None
    mode = str(spec.get("out_of_order") or "report")
    found = Backfill(mode=mode if mode in OUT_OF_ORDER else "report")
    if mode not in OUT_OF_ORDER:
        found.errors.append(
            "requirements.out_of_order is " + mode + ", not one of " + ", ".join(OUT_OF_ORDER)
            + " in ledger.config.json"
        )

    families = [str(f) for f in (spec.get("families") or [])]
    eligible = {i for fam, ids in data.ids.items() for i in ids if not families or fam in families}
    detail_of = {}
    for detail in data.details:
        detail_of.setdefault(detail.ident, detail)
    state = {row.ident: row.status for _fam, rows in sections for row in rows}
    invariant = {i for fam in data.families if "invariant" in fam.kind.lower() for i in data.ids.get(fam.family, [])}
    milestones = milestone_states(data)
    found.active = sorted(m for m, status in milestones.items() if status == "active")
    target_column = str(spec.get("target_column") or "")

    def target(ident):
        return column(data.rows.get(ident, []), data.headers.get(ident, []), target_column) if target_column else ""

    built_by, coming = {}, {}
    for order in data.orders:
        for ident in sorted(set(order.satisfies) | set(order.partial)):
            if ident not in eligible:
                continue
            if order.status == "done":
                built_by.setdefault(ident, []).append(order.slice_id)
            else:
                coming.setdefault(ident, []).append(order.slice_id)
            if order.status in BUILDING + ("done",) and ident not in detail_of:
                found.claimed_ahead.append((order, ident))
        claims = [i for i in set(order.satisfies) | set(order.partial) if i in eligible]
        if order.detail_read_on and not DATE.match(order.detail_read_on):
            found.errors.append(order.path + ": detail_read_on is " + order.detail_read_on + ", which is not a date")
        elif order.status in BUILDING and claims and not order.detail_read_on:
            found.unread.append(order)

    # **Built ahead, most urgent first.** A requirement a slice still to come will build on first,
    # because a correction to it grows with every slice stacked on the unratified reading; then an
    # invariant, which is a shape every area inherits; then what the active milestone is aimed at.
    ranked = []
    for ident in sorted(eligible):
        if ident in detail_of or not (built_by.get(ident) or state.get(ident) == INHERITED):
            continue
        why = []
        if coming.get(ident):
            why.append(", ".join(coming[ident]) + " builds on it")
        if ident in invariant:
            why.append("an invariant")
        if target(ident) and target(ident) in found.active:
            why.append(target(ident) + " is active")
        key = (not coming.get(ident), ident not in invariant, not (target(ident) in found.active), ident)
        ranked.append((key, (ident, target(ident), built_by.get(ident) or ["tests (" + MARK[INHERITED] + ")"], coming.get(ident, []), why)))
    found.ahead = [entry for _key, entry in sorted(ranked)]

    slices = {o.slice_id for o in data.orders}
    changes = {c.ident for c in data.changes}
    questions = {
        i for fam in data.families if "question" in fam.kind.lower()
        for i in set(data.ids.get(fam.family, [])) | {r for r in data.retired if family_for(r, data.families) is fam}
    }
    for detail in data.details:
        if detail.ident not in eligible or not detail.data:
            continue
        where = detail.path + ": "
        reviewed = scalar(detail.data.get("status")) == "reviewed"
        rows = reconciliation_rows(detail.body)
        for row in rows:
            label = where + "reconciliation row " + (row["against"] or "?") + " "
            decision = row["decision"].lower()
            named = set(TOKEN.findall(row["where"]))
            if not DATE.match(row["date"]):
                found.errors.append(label + "has the date " + (row["date"] or "empty") + ", which is not YYYY-MM-DD")
            if not row["against"]:
                found.errors.append(where + "a reconciliation row names nothing it was read against — a slice, or where the evidence came from")
            if decision not in RECONCILE_DECISIONS:
                found.errors.append(label + "decides " + (decision or "nothing") + ", not one of " + ", ".join(RECONCILE_DECISIONS))
            if row["by"] in BLANK:
                found.errors.append(label + "names nobody who decided it")
            if decision == "fix" and not named & slices:
                found.errors.append(label + "is a fix and names no slice that makes it — the work goes in the queue, not in this file")
            if decision == "change-request" and not named & changes:
                found.errors.append(label + "needs a change request and names none — raise it with /change-request and cite it")
            if decision == "open" and reviewed and not named & questions:
                found.errors.append(
                    label + "is still open on a reviewed file and names no registered question — a reviewed file"
                    " decides every conflict, or says which question holds it and who owns that"
                )

        revised = scalar(detail.data.get("revised_on")).strip()
        if not DATE.match(revised):
            continue
        for order in data.orders:
            if order.status not in BUILDING + ("done",) or detail.ident not in set(order.satisfies) | set(order.partial):
                continue
            read = order.detail_read_on
            if DATE.match(read) and read >= revised:
                continue
            if any(
                order.slice_id in TOKEN.findall(row["against"]) and DATE.match(row["date"]) and row["date"] >= revised
                for row in rows
            ):
                continue
            found.unreconciled.append((detail, order))

    late = {}
    for detail, order in found.unreconciled:
        late.setdefault(detail.ident, []).append(order.slice_id)
    for milestone, status in sorted(milestones.items()):
        if status not in CLOSED_MILESTONE:
            continue
        for ident in sorted(eligible):
            if target(ident) != milestone or not (built_by.get(ident) or state.get(ident) == INHERITED):
                continue
            detail = detail_of.get(ident)
            if detail is None:
                found.milestone.append((milestone, ident, "has no detail file"))
            elif scalar(detail.data.get("status")) != "reviewed":
                found.milestone.append((milestone, ident, "has a detail file nobody has reviewed"))
            if late.get(ident):
                found.milestone.append((milestone, ident, "is not reconciled with " + ", ".join(sorted(late[ident]))))
    return found


def check_order(found: Backfill) -> tuple:
    """`(errors, warnings)` for what arrived out of order, by `requirements.out_of_order`.

    A warning is never a list of fifty. Where the finding is a backlog rather than a defect — the
    queue a backfill works through — it is one line pointing at the table in `COVERAGE.md`, because
    a check that prints the same fifty lines on every run is read as noise by the second."""
    if found is None:
        return [], []
    mode = found.mode
    errors, warnings = list(found.errors), []

    gated = set()
    if mode == "fail":
        for order, ident in found.claimed_ahead:
            gated.add(ident)
            errors.append(
                order.path + ": " + order.slice_id + " claims " + ident + ", which has no detail file — under"
                " out_of_order: fail a slice is claimed only for a detailed requirement. A draft is enough:"
                " /requirement-detail " + ident
            )
    queued = [entry[0] for entry in found.ahead if entry[0] not in gated]
    if queued:
        warnings.append(
            str(len(queued)) + " requirement" + (" is" if len(queued) == 1 else "s are") + " built ahead of"
            " a detail file — the backfill queue in COVERAGE.md, most urgent first: " + ", ".join(queued[:5])
            + (" …" if len(queued) > 5 else "")
        )

    for order in found.unread:
        message = (
            order.path + ": " + order.slice_id + " is " + order.status + " and records no detail_read_on —"
            " the day it read the detail files of what it claims, so a later revision can be told apart"
        )
        (warnings if mode == "report" else errors).append(message)

    legacy = {}
    for detail, order in found.unreconciled:
        reviewed = scalar(detail.data.get("status")) == "reviewed"
        revised = scalar(detail.data.get("revised_on")).strip()
        if order.status in BUILDING and not order.detail_read_on:
            continue  # already said: it records no reading at all
        if order.status in BUILDING:
            message = (
                order.path + ": " + order.slice_id + " read " + detail.path + " on " + order.detail_read_on
                + " and it was revised on " + revised + " — re-read it and re-date detail_read_on, or raise"
                " the conflict"
            )
        elif not order.detail_read_on:
            # A finished slice from before anybody recorded a reading. Not a new drift, and not
            # knowable as one: reported, never failed, until a reconciliation row settles it.
            legacy.setdefault(detail.path, []).append(order.slice_id)
            continue
        else:
            message = (
                detail.path + ": " + order.slice_id + " was built against the reading of " + order.detail_read_on
                + ", and this file was revised on " + revised + " — reconcile them: a Reconciliation row"
                " against " + order.slice_id + ", dated no earlier than " + revised
            )
        strict = mode == "fail" or (mode == "backfill" and reviewed)
        (errors if strict else warnings).append(message)
    for path, orders in sorted(legacy.items()):
        warnings.append(
            path + ": " + ", ".join(sorted(orders)) + " recorded no reading of it and built what it"
            " describes — a Reconciliation row against each settles whether the build still holds"
        )

    for milestone, ident, missing in found.milestone:
        message = milestone + " is closed and " + ident + ", aimed at it and built, " + missing
        (warnings if mode == "report" else errors).append(message)
    return errors, warnings


