@dataclass
class WorkOrder:
    path: str
    slice_id: str
    title: str = ""
    phase: str = ""
    # What the slice is for. `feature` changes what the system can do; `characterisation` changes
    # nothing and writes the tests that pin what it already does. The second only exists because
    # of adoption: it is how an `≈` row becomes `●`, and it cannot be demonstrated the usual way
    # because there is nothing new to show.
    kind: str = "feature"
    size: str = ""
    # `estimated` is written at open and never corrected; `code_lines` is measured at close. The
    # gap between them is the only evidence there is for recalibrating the tiers, and correcting
    # the estimate to match the outcome is exactly how that evidence gets destroyed.
    estimated: int = 0
    code_lines: int = 0
    status: str = "queued"
    dep: str = "—"
    owner: str = ""
    depends_on: list = field(default_factory=list)
    touches: list = field(default_factory=list)
    satisfies: list = field(default_factory=list)
    partial: list = field(default_factory=list)
    adr: list = field(default_factory=list)
    demo: str = ""
    issue: str = ""
    # The day the slice read the detail files of what it claims — written at the claim. A detail
    # file revised after it is one the slice was not built against, and reconciling the two is
    # `DEVELOPMENT-PROCESS.md` §12.1.
    detail_read_on: str = ""
    body: str = ""


def slice_paths(root: str, config: dict, order) -> list:
    """Where a slice's summary may live: mirroring its work order's place in the tree.

    Mirroring rather than flattening is what keeps the two halves of one slice together as the
    directory grows a milestone and a phase level. A flat directory of sixty summaries is the
    thing this layout exists to prevent, and putting the summaries back into one would recreate
    it."""
    sub_dir = os.path.dirname(os.path.relpath(order.path, config["work_orders"]))
    base = os.path.join(root, config["slices"], sub_dir)
    return [
        os.path.join(base, order.slice_id + ".md"),
        os.path.join(base, order.slice_id.split("-")[-1] + ".md"),
    ]


def read_on(value) -> str:
    """A work order's `detail_read_on`, with every way of writing *none* read as empty — the same
    blanks a detail file's front matter is allowed."""
    text = scalar(value).strip()
    return "" if text in BLANK else text


def parse_work_orders(root: str, directory: str) -> list:
    orders = []
    # Recursive: work orders sit under `<milestone>/<phase>/`, and a flat directory still works
    # so the layout can be adopted without moving anything first.
    for path in sorted(glob.glob(os.path.join(root, directory, "**", "*.md"), recursive=True)):
        data, body = parse_front_matter(read(path))
        if not data:
            continue
        stem = os.path.splitext(os.path.basename(path))[0]
        orders.append(
            WorkOrder(
                path=os.path.relpath(path, root),
                slice_id=str(data.get("id") or stem),
                title=str(data.get("title") or ""),
                phase=str(data.get("phase") or ""),
                kind=str(data.get("kind") or "feature"),
                size=str(data.get("size") or ""),
                estimated=as_int(data.get("estimated")),
                code_lines=as_int(data.get("code_lines")),
                status=str(data.get("status") or "queued"),
                dep=str(data.get("dep") or "—"),
                owner=str(data.get("owner") or ""),
                depends_on=as_list(data.get("depends_on")),
                touches=as_list(data.get("touches")),
                satisfies=as_list(data.get("satisfies")),
                partial=as_list(data.get("partial")),
                adr=as_list(data.get("adr")),
                demo=str(data.get("demo") or ""),
                issue=str(data.get("issue") or "").lstrip("#").strip(),
                detail_read_on=read_on(data.get("detail_read_on")),
                body=body,
            )
        )
    return orders


