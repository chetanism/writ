def write_or_check(root: str, rel: str, content: str, check: bool) -> list:
    path = os.path.join(root, rel)
    if check:
        current = read(path) if os.path.exists(path) else ""
        if current != content:
            return [rel + " is stale. Run `python3 scripts/ledger.py`."]
        return []
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(content)
    return []


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Coverage ledger, slice queue, and process checks.")
    parser.add_argument("command", nargs="?", default="all", choices=["all", "ledger", "queue", "check"])
    parser.add_argument("--check", action="store_true", help="verify without writing")
    parser.add_argument("--root", default=".", help="project root")
    parser.add_argument("--config", default="scripts/ledger.config.json")
    args = parser.parse_args(argv)

    root = os.path.abspath(args.root)
    config = load_config(root, args.config)
    verify = args.check or args.command == "check"

    data = collect(root, config)
    sections, counts, unknown, unregistered, unclaimable = build_ledger(data)
    ordered, order_errors = order_slices(data.orders, config.get("phases", []))

    errors = []
    if args.command in ("all", "ledger", "check"):
        errors += write_or_check(
            root,
            config["coverage_out"],
            render_ledger(config, sections, counts, unregistered, unclaimable, data.details),
            verify,
        )

    if args.command in ("all", "queue", "check"):
        queue_path = os.path.join(root, config["queue_out"])
        if not os.path.exists(queue_path):
            errors.append(config["queue_out"] + " does not exist")
        else:
            spliced = splice_queue(read(queue_path), render_queue(config, ordered))
            if spliced is None:
                errors.append(config["queue_out"] + " has no " + QUEUE_BEGIN + " … " + QUEUE_END + " block")
            else:
                errors += write_or_check(root, config["queue_out"], spliced, verify)

    errors += order_errors
    if args.command == "check":
        satisfied = {r.ident for _f, rows in sections for r in rows if r.status == SATISFIED}
        errors += check_process(root, config, data, unknown, satisfied)
    else:
        errors += [p + ": [" + i + "] is not declared in " + f + "'s section" for p, i, f in unknown]
        errors += data.errors

    for message in sorted(set(errors)):
        sys.stderr.write("error: " + message + "\n")

    if not errors and args.command in ("all", "ledger", "check"):
        sys.stdout.write(
            "coverage: " + str(counts[SATISFIED]) + " satisfied, " + str(counts[PARTIAL]) + " partial, "
            + str(counts[NONE]) + " none, " + str(sum(counts.values())) + " total\n"
        )
    return 1 if errors else 0


if __name__ == "__main__":
    raise SystemExit(main())
