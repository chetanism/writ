# A placeholder is anything in angle brackets that is not markup: `<N>`, `<the gate commands>`,
# `<150>` and `<test:all>` all count. Case is not a signal — the templates use every shape — so the
# exemptions are for what Markdown itself carries: HTML tags, comments, and autolinked URLs.
PLACEHOLDER = re.compile(r"<([^<>\n]{1,80})>")
HTML_TAG = re.compile(r"^/?(?:a|b|i|p|br|hr|em|img|kbd|pre|sub|sup|div|span|code|strong|table|thead|tbody|tr|td|th|ul|ol|li|details|summary)(?:\s[^>]*)?/?$", re.I)


def placeholders(text: str) -> list:
    """Every unresolved `<...>` in `text`, in order, with the brackets kept for the message."""
    found = []
    for match in PLACEHOLDER.finditer(text):
        inner = match.group(1)
        if inner[0] in "!?" or inner[0].isspace() or inner[-1].isspace():
            continue  # a comment, a processing instruction, or `a < b > c` in prose
        if "://" in inner or inner.startswith("mailto:") or re.fullmatch(r"[^\s@]+@[^\s@]+", inner):
            continue  # an autolink
        if HTML_TAG.match(inner):
            continue
        found.append("<" + inner + ">")
    return found
FENCE = re.compile(r"```[^\n]*\n(.*?)```", re.S)
NUMBERED = re.compile(r"^\s*\d+\.\s+\S", re.M)


INLINE_CODE = re.compile(r"`[^`\n]*`")


def prose_lines(text: str):
    """(line number, line) for every line of prose — outside fenced blocks, outside inline code,
    and outside blockquotes.

    Code is notation, not a gap: `/slice-open <id>`, `slice/<ID>-<slug>` and `git diff
    <last-pass>..HEAD` are how a finished document describes a shape, and they must survive. A
    blockquote is guidance that the bootstrap deletes. What is left is where a placeholder to fill
    can only be a placeholder — which is why the templates keep theirs out of backticks."""
    fenced = False
    for number, line in enumerate(text.split("\n"), start=1):
        if re.match(r"^\s*(```|~~~)", line):
            fenced = not fenced
            continue
        if fenced or line.strip().startswith(">"):
            continue
        yield number, INLINE_CODE.sub("`…`", line)


def demo_section(body: str) -> str:
    """The text under the first heading whose title starts with `Demo`."""
    lines = body.split("\n")
    start, level = None, 0
    for index, depth, raw in headings(lines):
        if start is None:
            if normalise(raw).startswith("demo"):
                start, level = index, depth
            continue
        if depth <= level:
            return "\n".join(lines[start + 1 : index])
    return "" if start is None else "\n".join(lines[start + 1 :])


def check_process(root: str, config: dict, data: Collected, unknown, satisfied=frozenset()) -> list:
    errors = list(data.errors)
    errors += check_details(config, data, set(satisfied))

    for path, ident, fam in unknown:
        errors.append(path + ": [" + ident + "] is not declared in " + fam + "'s section")

    seen = {}
    for order in data.orders:
        if order.slice_id in seen:
            errors.append(order.path + ": slice id " + order.slice_id + " is already used by " + seen[order.slice_id])
        seen[order.slice_id] = order.path

        # An ADR named by a work order exists before implementation starts. A decision recorded
        # after the fact is a justification; the record is only worth keeping if it precedes
        # the code it governs.
        for adr in order.adr:
            number = adr.split("-", 1)[-1]
            here = os.path.join(root, config["decisions"])
            candidates = []
            for stem in (number, adr, adr.lower()):
                candidates += glob.glob(os.path.join(here, stem + "-*.md"))
                candidates += glob.glob(os.path.join(here, stem + ".md"))
            if not candidates:
                errors.append(order.path + ": names " + adr + ", and no such record exists in " + config["decisions"])

        # A slice is not demonstrable in the abstract. Either a script a reader can paste, or
        # numbered steps through an interface with a stated expected observation.
        demo = demo_section(order.body)
        if not demo.strip():
            errors.append(order.path + ": has no Demo section")
        else:
            blocks = [b for b in FENCE.findall(demo) if [l for l in b.split("\n") if l.strip() and not l.strip().startswith("#")]]
            steps = NUMBERED.findall(demo)
            if order.demo == "ui":
                if len(steps) < 2 or "expected" not in demo.lower():
                    errors.append(order.path + ": demo is `ui` and needs numbered steps and an Expected line")
            elif not blocks:
                errors.append(order.path + ": demo is `script` and carries no runnable code block")
            for hit in placeholders(demo):
                errors.append(order.path + ": demo still carries the placeholder " + hit + " — nobody types an identifier")

        if order.status == "done":
            summary = os.path.join(root, config["slices"], order.slice_id + ".md")
            alt = os.path.join(root, config["slices"], order.slice_id.split("-")[-1] + ".md")
            if not os.path.exists(summary) and not os.path.exists(alt):
                errors.append(order.path + ": status is done and " + os.path.relpath(summary, root) + " does not exist")

    limit = int(config.get("wip_limit") or 0)
    if limit:
        active = [o for o in data.orders if o.status in ("in-progress", "in-review")]
        if len(active) > limit:
            errors.append("work in progress is " + str(len(active)) + ", over the limit of " + str(limit))
        for i, one in enumerate(active):
            for other in active[i + 1 :]:
                shared = sorted(set(one.touches) & set(other.touches))
                if shared:
                    errors.append(
                        one.slice_id + " and " + other.slice_id + " are both active and both touch "
                        + ", ".join(shared) + " — serialise them or split the surface"
                    )

    scan = config.get("placeholder_scan", {})
    for path in iter_files(root, scan.get("include", []), scan.get("exclude", [])):
        for line_no, line in prose_lines(read(path)):
            for hit in placeholders(line):
                errors.append(
                    os.path.relpath(path, root) + ":" + str(line_no) + ": unresolved placeholder " + hit
                )

    return errors


