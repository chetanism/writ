# Source 4 — test annotations
# --------------------------------------------------------------------------------------------

QUOTED = re.compile(r"""(['"`])(.*?)\1""")


def parse_annotations(root: str, tests: dict) -> list:
    """Every `[ID]` occurrence in a test file, with the enclosing test name as its proof.

    Parsing source text is deliberate: this reports what the suite *claims* to prove. That the
    suite passes is a separate gate step, and conflating the two would let a skipped test count
    as evidence without anyone noticing which of the two failed."""
    pattern = re.compile(tests["annotation"])
    hits = []
    for path in iter_files(root, tests["globs"], tests.get("exclude", [])):
        rel = os.path.relpath(path, root)
        try:
            content = read(path)
        except (UnicodeDecodeError, OSError):
            continue
        for line in content.split("\n"):
            for match in pattern.finditer(line):
                ident = match.group("id")
                proof = match.groupdict().get("proof")
                if not proof:
                    quoted = [q.group(2) for q in QUOTED.finditer(line) if "[" + ident + "]" in q.group(2)]
                    proof = quoted[0] if quoted else line.strip()
                hits.append((ident, proof.strip(), rel))
    return sorted(set(hits))


# --------------------------------------------------------------------------------------------
# Source 5 — requirement detail files
# --------------------------------------------------------------------------------------------
#
# One file per requirement, saying what a person would *see* if it held. It is not a coverage
# source — a requirement is proven by its tests — but it is what a manual test case is written
# from, and what a verification run judges against. Nothing else fills that gap: a slice spans
# several requirements and proves its own claims, not theirs.
#
# The whole risk of a second document per requirement is that it becomes a second specification
# which quietly disagrees with the first. Hence the quote: a detail file carries the requirement's
# own words, character for character, and this checks them. When the specification is amended the
# file fails until somebody has read the amendment.

DETAIL_STATUSES = ("draft", "reviewed")
DETAIL_VERDICTS = ("implemented", "gap", "absent", "detail-wrong")
DETAIL_KEYS = ("id", "area", "status", "drafted_by", "approved_by", "reviewed_against", "surface")
DETAIL_SECTIONS = (
    "The requirement",
    "What it means in the application",
    "Actors",
    "Preconditions and data",
    "Observable behaviour",
    "Boundary and negative cases",
    "Out of scope",
    "Open questions",
    "Related",
    "Verification",
)
BLANK = (None, "", "-", "—", "TBD", "tbd")


@dataclass
class Detail:
    path: str
    ident: str
    data: dict
    body: str


def area_of(ident: str) -> str:
    """`FR-ACC-01` files under `FR-ACC`, `INV-1` under `INV`. The directory is derived from the
    identifier, so it is one less thing to keep in step."""
    return ident.rsplit("-", 1)[0]


def scalar(value) -> str:
    """Front matter yields a list for an empty value and for a bracketed one. Either way a field
    that names nobody reads as blank."""
    if isinstance(value, list):
        return ", ".join(str(v) for v in value)
    return "" if value is None else str(value)


def parse_details(root: str, directory: str) -> list:
    if not directory:
        return []
    details = []
    for path in sorted(glob.glob(os.path.join(root, directory, "**", "*.md"), recursive=True)):
        if os.path.basename(path).lower() == "readme.md":
            continue
        data, body = parse_front_matter(read(path))
        details.append(
            Detail(
                path=os.path.relpath(path, root),
                ident=os.path.splitext(os.path.basename(path))[0],
                data=data,
                body=body,
            )
        )
    return details


def quoted(body: str) -> str:
    """The blockquote under *The requirement*, unwrapped to one line.

    Joined and whitespace-collapsed so that wrapping a long requirement across several `>` lines
    is a formatting choice rather than a failure."""
    want, inside, lines = normalise(DETAIL_SECTIONS[0]), False, []
    for line in body.split("\n"):
        if line.lstrip().startswith("#"):
            if lines:
                break
            inside = normalise(line.lstrip("#")) == want
            continue
        if inside and line.strip().startswith(">"):
            lines.append(line.strip()[1:].strip())
        elif lines and not line.strip():
            break
    return re.sub(r"\s+", " ", " ".join(lines)).strip()


def section_titles(body: str) -> list:
    return [normalise(t) for _i, depth, t in headings(body.split("\n")) if depth == 2]


def verification_verdicts(body: str) -> list:
    """The second cell of every row under *Verification*, which is where a run records what it
    found. A vocabulary rather than prose: *mostly works* is the verdict this exists to refuse."""
    found, in_table = [], False
    for line in section_lines(body, DETAIL_SECTIONS[-1]):
        stripped = line.strip()
        if not stripped.startswith("|"):
            in_table = False
            continue
        if is_separator(line):
            continue
        col = cells(line)
        if len(col) < 2:
            continue
        if bare(col[0]).lower() == "date":
            in_table = True
            continue
        if in_table and bare(col[0]):
            found.append(bare(col[1]))
    return found


def check_details(config: dict, data: Collected, satisfied: set) -> list:
    """Every way a detail file can be wrong about the requirement it names."""
    spec = config.get("requirements") or {}
    directory = spec.get("dir") or ""
    if not directory:
        return []

    families = [str(f) for f in (spec.get("families") or [])]
    eligible = {i for fam, ids in data.ids.items() for i in ids if not families or fam in families}
    phase_pattern = str(spec.get("phase_pattern") or "")
    errors = []

    for detail in data.details:
        where = detail.path + ": "
        if not detail.data:
            errors.append(where + "has no front matter")
            continue

        ident = detail.ident
        if scalar(detail.data.get("id")) != ident:
            errors.append(where + "declares id " + scalar(detail.data.get("id")) + " and is filed as " + ident)
        if ident not in eligible:
            # Two different mistakes, and the difference matters: a withdrawn requirement is
            # struck through and thereby undeclared, so its file has outlived it.
            declared = {i for ids in data.ids.values() for i in ids}
            if ident in declared:
                errors.append(where + ident + " belongs to no family the detail track covers (" + ", ".join(families) + ")")
            else:
                errors.append(where + ident + " is not declared in the specification")
            continue

        area = area_of(ident)
        leaf = os.path.basename(os.path.dirname(detail.path))
        if leaf != area:
            errors.append(where + "sits under " + leaf + " and its identifier files under " + area)
        if scalar(detail.data.get("area")) != area:
            errors.append(where + "declares area " + scalar(detail.data.get("area")) + " and its identifier files under " + area)

        # `approved_by` is the exception: a draft has no approver, and the pair is checked below.
        for key in (k for k in DETAIL_KEYS if k != "approved_by"):
            if scalar(detail.data.get(key)).strip() in BLANK:
                errors.append(where + "front matter has no " + key)

        status = scalar(detail.data.get("status"))
        if status not in DETAIL_STATUSES:
            errors.append(where + "status is " + (status or "empty") + ", not one of " + ", ".join(DETAIL_STATUSES))
        if status == "reviewed" and scalar(detail.data.get("approved_by")).strip() in BLANK:
            errors.append(where + "is reviewed and names no approver — a review nobody signed is a draft")

        row = data.rows.get(ident) or []
        source = bare(row[1]) if len(row) > 1 else ""
        if source and re.sub(r"\s+", " ", source) != quoted(detail.body):
            errors.append(
                where + "quotes " + ident + " differently from the specification. The requirement "
                "was amended, or the quote was edited — re-read it, correct the quote and re-date "
                "reviewed_against"
            )
        # Whatever the declaring table uses to phase its requirements, mirrored. A table that
        # carries no such column — an invariant's, typically — is simply not checked.
        phase = ""
        if phase_pattern:
            phase = next((bare(c) for c in row[1:] if re.fullmatch(phase_pattern, bare(c))), "")
        if phase and scalar(detail.data.get("phase")) != phase:
            errors.append(
                where + "says " + (scalar(detail.data.get("phase")) or "no phase")
                + " and the specification says " + phase
            )

        present = section_titles(detail.body)
        for title in DETAIL_SECTIONS:
            if normalise(title) not in present:
                errors.append(where + "has no " + title + " section")

        for verdict in verification_verdicts(detail.body):
            if verdict not in DETAIL_VERDICTS:
                errors.append(where + "records the verdict " + verdict + ", not one of " + ", ".join(DETAIL_VERDICTS))

    seen = {}
    for detail in data.details:
        if detail.ident in seen:
            errors.append(detail.path + ": " + detail.ident + " is already detailed by " + seen[detail.ident])
        seen[detail.ident] = detail.path

    # Off by default, because turning it on with a backlog fails the gate for work nobody has been
    # asked for yet. It is what closes the track once the backlog is cleared.
    if spec.get("require_detail_for_satisfied"):
        for ident in sorted(satisfied & eligible):
            if ident not in seen:
                errors.append(ident + " is satisfied and has no detail file under " + directory)
    return errors


