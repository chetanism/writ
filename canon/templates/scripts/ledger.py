def order_slices(orders: list, phases: list):
    """Topological sort of `depends_on`, tie-broken by phase order then slice id.

    Returns (ordered, errors). A dependency on an unknown slice and a cycle are both errors:
    a queue that cannot be linearised is not an ordering, and picking one arbitrarily hides it.
    """
    errors = []
    letters = [p.get("letter", "") for p in phases] if phases else []
    index = {order.slice_id: order for order in orders}

    def rank(order: WorkOrder):
        phase = order.phase or ""
        position = letters.index(phase) if phase in letters else len(letters)
        return (position, order.slice_id)

    incoming = {}
    for order in orders:
        deps = []
        for dep in order.depends_on:
            if dep not in index:
                errors.append(order.path + ": depends_on names " + dep + ", which is not a work order")
            else:
                deps.append(dep)
        incoming[order.slice_id] = set(deps)

    ready = sorted([o for o in orders if not incoming[o.slice_id]], key=rank)
    ordered = []
    while ready:
        current = ready.pop(0)
        ordered.append(current)
        changed = []
        for other in orders:
            if current.slice_id in incoming[other.slice_id]:
                incoming[other.slice_id].discard(current.slice_id)
                if not incoming[other.slice_id]:
                    changed.append(other)
        ready = sorted(ready + changed, key=rank)

    if len(ordered) < len(orders):
        stuck = sorted(o.slice_id for o in orders if o not in ordered)
        errors.append("depends_on forms a cycle among " + ", ".join(stuck))
        ordered += [o for o in orders if o not in ordered]

    return ordered, errors


def render_queue(config: dict, ordered: list) -> str:
    team = config.get("mode") == "team"
    tracked = bool(config.get("tracker"))
    header = (
        "| # | ID | Phase | Size | Dep | Status | "
        + ("Owner | " if team else "")
        + ("Issue | " if tracked else "")
        + "Slice | Advances |"
    )
    rule = "|--:|---|:--:|:--:|:--:|:--:|" + (":--:|" if team else "") + (":--:|" if tracked else "") + "---|---|"
    out = [
        QUEUE_BEGIN,
        "",
        "<!-- Written by `python3 scripts/ledger.py queue` from work-order front matter.",
        "     Edit the work order, not this block. Prose around it is hand-written. -->",
        "",
        header,
        rule,
    ]
    for position, order in enumerate(ordered, start=1):
        advances = ", ".join(order.satisfies + [p + " (partial)" for p in order.partial])
        row = [
            str(position),
            "**" + order.slice_id + "**",
            order.phase,
            order.size,
            order.dep,
            order.status,
        ]
        if team:
            row.append(order.owner or "—")
        if tracked:
            row.append("#" + order.issue if order.issue and order.issue != "—" else "—")
        row += [escape(order.title), advances]
        out.append("| " + " | ".join(row) + " |")
    out += ["", QUEUE_END]
    return "\n".join(out)


def splice_queue(existing: str, block: str):
    """Replace the generated block in place. The surrounding prose is the human's."""
    if QUEUE_BEGIN not in existing or QUEUE_END not in existing:
        return None
    head = existing.split(QUEUE_BEGIN)[0]
    tail = existing.split(QUEUE_END, 1)[1]
    return head + block + tail


