@dataclass(frozen=True)
class Family:
    family: str
    pattern: str
    owner: str
    section: str
    kind: str
    traceable: bool


def parse_registry(text: str) -> list:
    """Read the `| Family | Pattern | Owner | Declared in | Kind | Traceable |` table."""
    families = []
    for line in text.split("\n"):
        if not line.strip().startswith("|") or is_separator(line):
            continue
        col = cells(line)
        if len(col) < 6:
            continue
        name = bare(col[0])
        if not re.fullmatch(r"[A-Za-z][A-Za-z0-9]*", name) or name.lower() == "family":
            continue
        families.append(
            Family(
                family=name,
                pattern=bare(col[1]),
                owner=bare(col[2]),
                section=bare(col[3]),
                kind=bare(col[4]),
                traceable="yes" in col[5].lower(),
            )
        )
    return families


