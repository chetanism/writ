@dataclass
class Row:
    ident: str
    status: str
    slices: list
    proofs: list
    unproven: bool


def build_ledger(data: Collected):
    traceable = [f for f in data.families if f.traceable]
    known = {f.family for f in data.families}
    declared = {i for fam in data.ids.values() for i in fam}

    claims_satisfies: dict = {}
    claims_partial: dict = {}
    for order in data.orders:
        for ident in order.satisfies:
            claims_satisfies.setdefault(ident, set()).add(order.slice_id)
        for ident in order.partial:
            claims_partial.setdefault(ident, set()).add(order.slice_id)

    proofs: dict = {}
    for ident, proof, path in data.annotations:
        proofs.setdefault(ident, []).append((proof, path))

    unknown, unregistered = [], {}
    for ident, _proof, path in data.annotations:
        if ident in declared:
            continue
        fam = family_for(ident, data.families)
        if fam is None or fam.family not in known:
            unregistered.setdefault(ident, set()).add(path)
        else:
            unknown.append((path, ident, fam.family))

    unclaimable = {}
    for ident in sorted(set(claims_satisfies) | set(claims_partial)):
        if ident in declared:
            continue
        fam = family_for(ident, data.families)
        who = sorted(claims_satisfies.get(ident, set()) | claims_partial.get(ident, set()))
        if fam is None:
            unclaimable[ident] = who
        else:
            for slice_id in who:
                unknown.append((slice_id, ident, fam.family))

    sections = []
    counts = {SATISFIED: 0, PARTIAL: 0, NONE: 0}
    for fam in traceable:
        rows = []
        for ident in data.ids[fam.family]:
            sats = claims_satisfies.get(ident, set())
            pars = claims_partial.get(ident, set())
            tests = sorted(set(proofs.get(ident, [])))
            if sats and tests:
                status = SATISFIED
            elif sats or pars or tests:
                status = PARTIAL
            else:
                status = NONE
            counts[status] += 1
            rows.append(
                Row(
                    ident=ident,
                    status=status,
                    slices=sorted(sats | pars),
                    proofs=[p for p, _ in tests],
                    unproven=bool(sats) and not tests,
                )
            )
        sections.append((fam, rows))

    return sections, counts, sorted(set(unknown)), unregistered, unclaimable


