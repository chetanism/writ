# Source 2 — declared identifiers
# --------------------------------------------------------------------------------------------


def section_lines(text: str, section: str) -> list:
    """The lines of `section`, from its heading to the next heading of the same or higher level.

    Subsections are included and siblings are not. A section of `*` is the whole document."""
    lines = text.split("\n")
    if section.strip() == "*":
        return lines
    want = normalise(section)
    start = None
    level = 0
    for index, depth, raw in headings(lines):
        title = normalise(raw)
        if start is None:
            if title == want or title.startswith(want) or (title and want.startswith(title)):
                start, level = index, depth
            continue
        if depth <= level:
            return lines[start + 1 : index]
    return [] if start is None else lines[start + 1 :]


def declared_rows(text: str, section: str) -> list:
    """(identifier, cells) for every declaring row, in document order.

    The whole row rather than its first cell, because the requirement's own words are the second
    cell and the detail track quotes them verbatim. Nothing else may restate a requirement: a
    second wording of one is a second requirement, discovered the day the two disagree."""
    found, in_table = [], False
    for line in section_lines(text, section):
        stripped = line.strip()
        if not stripped.startswith("|"):
            in_table = False
            continue
        if is_separator(line):
            continue
        col = cells(line)
        if not col:
            continue
        first = bare(col[0])
        if first.lower() == "id":
            in_table = True
            continue
        if in_table and first:
            found.append((first, col))
    return found


def declared_ids(text: str, section: str) -> list:
    """Every first-cell value of a table whose header row begins `| ID |`, inside `section`."""
    return [ident for ident, _cells in declared_rows(text, section)]


